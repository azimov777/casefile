#!/bin/sh
# Кладёт рядом со статикой конфигурацию установки — `/config.json` с ключом, который
# приложение берёт само, не спрашивая человека (`src/shared/api/install-config.ts`).
#
# Запускает его штатный вход образа nginx: он выполняет `/docker-entrypoint.d/*.sh`
# по порядку имён и только потом стартует сервер. Номер 40 — после `20-envsubst-on-
# templates.sh`, который разворачивает конфигурацию из шаблона.
#
# Ключ в образ не попадает: файл рождается при старте контейнера. Нет ни переменной,
# ни смонтированного файла — конфигурации нет, и это норма, а не поломка: интерфейс
# покажет экран входа. Так поднимают установку, где людей несколько и ключ у каждого
# свой.
set -eu

target=/usr/share/nginx/html/config.json

# Два источника, потому что контуры разные. Переменную задаёт compose (значение читает
# на хосте скрипт подъёма), файл монтируют туда, где секрет не должен появляться
# в окружении контейнера: `docker run -v /путь/ui-token:/run/secrets/ui-token:ro`.
token=${TRACKER_UI_TOKEN:-}
token_file=${TRACKER_UI_TOKEN_FILE:-/run/secrets/ui-token}

if [ -z "$token" ] && [ -f "$token_file" ]; then
  # Файл содержит только секрет и без перевода строки в конце (`../tracker`, команда
  # `local-token`). Подстановка команды срезает перевод строки, если он всё же появится:
  # из такого значения браузер не собрал бы заголовок.
  token=$(cat "$token_file")
fi

if [ -z "$token" ]; then
  # Файл от прошлого запуска пережить снятие ключа не должен: слой со статикой живёт
  # столько же, сколько контейнер, и перезапуск без ключа иначе продолжал бы раздавать
  # прежний.
  rm -f "$target"
  echo "$0: ключа установки нет, /config.json не создан — интерфейс покажет экран входа"
  exit 0
fi

case $token in
  *[!A-Za-z0-9_.:~+/=-]*)
    # Кавычка, обратная косая или перевод строки собрали бы неразборчивый JSON, а его
    # приложение читает как «ключа нет» — то есть поломка контура выглядела бы нормой.
    # Лучше не подняться: пустой экран входа на локальной установке ничего не объясняет.
    echo "$0: ключ установки содержит недопустимые символы, /config.json не создан" >&2
    rm -f "$target"
    exit 1
    ;;
esac

# Секрет не печатается никогда: вывод этого скрипта уходит в журнал контейнера, а его
# читают и показывают.
printf '{"token":"%s"}' "$token" >"$target"
chmod 0644 "$target"
echo "$0: ключ установки положен в $target"
