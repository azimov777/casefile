/**
 * Ключ черновика замечания.
 *
 * Сам черновик общий (`shared/lib`, `draft.ts`). Своё у замечания одно: оно про
 * задачу целиком, а не про запись в ней, — поэтому в ключе только ключ задачи. Второе
 * замечание к той же задаче человек пишет после того, как отправил первое.
 */
export function remarkDraftKey(taskKey: string): string {
  return `tracker.remark.${taskKey}`;
}
