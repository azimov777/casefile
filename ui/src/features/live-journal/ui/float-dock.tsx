import { useState, type ReactNode } from 'react';
import { cn } from '@/shared/lib';
import { BarSlot } from '../model/bar-slot';

interface FloatDockProps {
  /** Оболочка целиком: полосу рисует страница, и место ей должно быть видно оттуда. */
  children: ReactNode;
  /** Стопка уведомлений о вопросах: её рисует сама оболочка. */
  stack: ReactNode;
}

/**
 * Низ области содержания — одно место на два плавающих слоя: полосу обновлений
 * таблицы и стопку уведомлений о вопросах. Оба вне потока вёрстки и ничего на странице
 * не сдвигают, а внутри этого места лежат обычным потоком — тем же приёмом, что
 * карточки внутри самой стопки.
 *
 * Помещаются рядом — стоят рядом: полоса у левого края, стопка у правого, как стояли
 * всегда. Не помещаются — стопка встаёт строкой выше полосы. Рядом им тесно
 * не на краю, а на целом диапазоне: на `fold` боковая панель, полоса и карточка
 * предельной ширины вместе с полями шире окна, и никакой сдвиг по горизонтали этого
 * не лечит (`UI-98#13`). Отдельными `fixed` в своих углах они там ложились друг
 * на друга, и «Показать» уходило под карточку.
 *
 * Внизу стоит полоса, а не стопка. Стопка растёт вверх сама, с каждым пришедшим
 * вопросом: полоса над ней поднималась бы с каждой карточкой, и «Показать» уезжало бы
 * из-под курсора. Полоса же — одна строка постоянной высоты, и стопка над ней сдвигается,
 * только когда полоса приходит или уходит.
 *
 * Этот сдвиг едет, а не прыгает (UI-101): у полосы своё место, и оно открывается
 * и закрывается строками сетки — тем же движением, что место карточки в стопке.
 * Место рисует сама полоса вместе с собой (`updates-bar.tsx`): только она знает, когда
 * приходит и когда уходит, а уходящую держит невидимой, пока место схлопывается.
 * До UI-101 это была названная цена — стопка вставала над пришедшей полосой в один кадр.
 *
 * Поэтому промежуток у места только между соседями по строке (`gap-x-2`). Между
 * строками — стопкой и полосой под ней — промежуток живёт полем самой полосы внутри её
 * места: зазор строк появлялся бы в тот кадр, когда появилась вторая строка, и не уехал
 * бы вместе с местом (`docs/notes/ui.md`, «Промежуток между соседями не уезжает вместе
 * с местом»).
 *
 * Рядом или одна над другой, решает раскладка, а не медиазапрос: хватит ли места,
 * зависит от ширины области содержания (окно без панели) и от текста полосы (язык,
 * число), а не от ширины окна (`docs/notes/ui.md`, «Порог, посчитанный по окну, врёт
 * там, где часть окна занята панелью»). `flex-wrap: wrap-reverse` кладёт следующую
 * строку над первой, а не под ней; `items-start` поэтому прижимает к **нижнему** краю
 * строки — при `wrap-reverse` начало поперечной оси внизу.
 *
 * Стопка переносится по своему пределу ширины, а не по нынешней: место под неё
 * берётся `basis-(--ui-float-max)`, а карточки внутри по-прежнему по своему тексту.
 * Иначе вопрос с длинным заголовком, пришедший к короткому, расширил бы стопку и рывком
 * перенёс бы её вместе с уже прочитанной карточкой над полосой.
 *
 * Место тянется во всю ширину области содержания, и пустая его часть лежит поверх
 * строк таблицы и листания: указатель ловят только полоса и карточки
 * (`pointer-events`), а не само место.
 *
 * Левый край — край области содержания, а не окна: на `fold` угол окна занят подвалом
 * боковой панели — участником и кнопкой «Выйти» (UI-98). Отступ тот же, что от края окна
 * без панели, только считается от её края; `--ui-side` берётся токеном, а не числом —
 * разойдясь с шириной панели, место однажды снова легло бы на подвал.
 */
export function FloatDock({ children, stack }: FloatDockProps) {
  const [slot, setSlot] = useState<HTMLElement | null>(null);

  return (
    <BarSlot.Provider value={slot}>
      {children}
      <div
        className={cn(
          'pointer-events-none fixed right-4 bottom-4 left-4 z-10',
          'fold:left-[calc(var(--ui-side)+var(--spacing)*4)]',
          'flex flex-wrap-reverse items-start gap-x-2',
        )}
      >
        {/* Узел для портала полосы: своей коробки у него нет, и соседом стопки
            становится место, которое полоса рисует вместе с собой. */}
        <div ref={setSlot} className="contents" />
        <div className="ml-auto flex basis-(--ui-float-max) justify-end">{stack}</div>
      </div>
    </BarSlot.Provider>
  );
}
