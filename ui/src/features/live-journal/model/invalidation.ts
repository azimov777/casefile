import type { QueryKey } from '@tanstack/react-query';
import { questionKeys } from '@/entities/entry';
import { sessionKeys } from '@/entities/session';
import { taskKeys } from '@/entities/task';
import type { JournalFrame } from './frames';

/**
 * Что устарело от записи — и делится ли это на то, что можно перечитать прямо сейчас.
 *
 * Граница проходит не по «важности», а по тому, двигает ли обновление то, на что
 * человек смотрит. Карточка открытой задачи, входящая и счётчик вопросов дополняются
 * сверху и в сторону — прокрутка от них не сбивается, а ждёт человек как раз их.
 * Список же и доска пересобирают порядок и состав строк: строка из-под курсора
 * уезжает, и промах по ссылке ведёт не туда.
 */
export interface Invalidation {
  /** Перечитывается сразу: обновление ничего не сдвигает. */
  immediate: QueryKey[];
  /** Ждёт просьбы человека: обновление переставит строки. */
  deferred: QueryKey[];
}

/**
 * Что устарело от этой записи.
 *
 * Кадр в кэш не пишется: интерфейс не вычисляет за бэкенд (`CONCEPT.md`, 6). Признаки
 * задачи, счётчик вопросов и состав выдачи считаются на сервере из дела и связей —
 * дописать их «по кадру» значит однажды показать не то, что там на самом деле.
 *
 * Ключи заданы префиксами: `['task', 'DEMO-6']` накрывает и пакет карточки, и ленту
 * дела, и прочитанные тела записей этой задачи.
 */
export function keysToInvalidate(frame: JournalFrame): Invalidation {
  const immediate: QueryKey[] = [['task', frame.taskKey]];

  // Вопрос и ответ меняют «входящую» и счётчик в шапке. Это и есть «требует внимания»:
  // ради этого человек держит вкладку открытой, и ждать его согласия здесь нечего.
  if (frame.type === 'question' || frame.type === 'answer') {
    immediate.push(questionKeys.all, sessionKeys.bootstrap);
  }

  // Любая запись меняет `updated_at` задачи, а часто и её признаки: список и доска
  // устаревают от чего угодно — и потому ждут просьбы.
  return { immediate, deferred: [taskKeys.all] };
}

/**
 * Что перечитать после обрыва связи.
 *
 * За время паузы могло случиться что угодно, а догонять пропущенные кадры поштучно
 * интерфейс не станет. Деление то же: открытая задача, входящая и счётчик обновляются
 * сами, список — по просьбе. Переподключение случается ровно тогда, когда человек
 * ничего не делал, и переставлять строки под ним особенно нечестно.
 */
export function keysAfterReconnect(): Invalidation {
  return {
    immediate: [['task'], questionKeys.all, sessionKeys.bootstrap],
    deferred: [taskKeys.all],
  };
}
