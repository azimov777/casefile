interface TasksBoardProps {
  /** Отбор человека без статуса: свой статус дописывает к нему сам столбец. */
  params: TaskListParams;
  /**
   * Отказ уже объяснён формой отбора — столбцы о нём молчат. Иначе один и тот же
   * разбор запроса объяснялся бы разом в шести местах: непрочитанный столбец
   * не знает, что он такой не один.
   */
  explained: boolean;
  /**
   * Свёрнутые столбцы. Приходят из адреса, а не из своего `useState`: свёрнутое
   * состояние — это то, что человек увидит по пересланной ссылке, и терять его на
   * переходе в таблицу и обратно незачем.
   */
  collapsed: TaskStatus[];
  onToggle: (status: TaskStatus, open: boolean) => void;
}

/**
 * Доска: те же задачи одной очереди, разложенные по столбцам статусов.
 *
 * Перечень и порядок столбцов берутся из перечисления статуса сгенерированного клиента
 * (`TASK_STATUSES`), а не из своего списка: перечисление уже менялось и может измениться
 * снова — доска обязана пережить это перегенерацией клиента, без правки кода
 * (`docs/FRONTEND.md`, «Доска без доски»).
 *
 * Задач доска не получает и не раздаёт: каждый столбец читает свой отбор сам и своим
 * курсором (UI-70). Общего дочитывания под доской поэтому нет вовсе — способ дочитать
 * столбец ровно один, и это его прокрутка.
 */
export function TasksBoard({ params, explained, collapsed, onToggle }: TasksBoardProps) {
  /*
   * Доска высотой в остаток окна: столбец прокручивается внутри себя, а страница
   * под ним не двигается вовсе (UI-68).
   *
   * Остаток считается замером, а не одним `calc`, потому что над доской нет ни одной
   * величины, известной заранее: верхняя полоса задана минимумом и растёт от
   * увеличенного текста, заголовок с формой отбора переносится по ширине окна и
   * раскрывается по нажатию. Замеряется только отступ доски от верха документа —
   * своя высота доски в него не входит, поэтому обратной связи «выросла — пересчитали —
   * снова выросла» здесь нет. Всё, что ниже ряда столбцов, раздаёт уже флексбокс:
   * ряд забирает остаток (`flex-1` при `min-h-0`).
   *
   * Вычитается `--ui-board-tail` (1rem), а не общий хвост страницы `--ui-page-tail`
   * (3rem): тот рассчитан на экраны, которые прокручиваются сами и заканчиваются
   * пустотой после последнего блока, а у доски высота и так точная — вторая пустота
   * под ней читалась бы лишним полем (UI-129, было около 48 px пустой полосы под
   * полосой прокрутки столбцов). `app-shell.tsx` подменяет хвост оболочки этим же
   * токеном по признаку `data-board` ниже — источник нижнего края доски один.
   *
   * `pin-scope` — шкала прокрутки, по которой заголовки столбцов ниже точки остановки
   * держатся у верха окна (UI-94, см. заголовок в `BoardColumn`). Объявлена здесь,
   * а не на ряду, и это условие: шкала считается от ближайшего порта прокрутки, у доски
   * это окно, а у ряда — он сам.
   */
  const boardRef = useRef<HTMLDivElement>(null);
  const [top, setTop] = useState(0);

  useLayoutEffect(() => {
    const board = boardRef.current;
    if (board === null) return;
    const measure = () => {
      setTop(Math.round(board.getBoundingClientRect().top + window.scrollY));
    };
    measure();

    /*
     * Наблюдают за родителем, а не за `document.body`: `body` объявлен `height: 100%`
     * (`shared/styles/reset.css`), его рамка равна окну всегда, и раскрытая форма
     * отбора его не меняет — доска съезжала вниз, оставаясь прежней высоты, и страница
     * снова начинала прокручиваться. Родитель растёт вместе с тем, что стоит над
     * доской, и это ровно то событие, из-за которого замер устарел.
     */
    const above = board.parentElement;
    const observer = new ResizeObserver(() => {
      // Через кадр: пересчёт идёт из обработчика наблюдателя, и без этого браузер
      // ругается на не доставленные за проход уведомления.
      window.requestAnimationFrame(measure);
    });
    if (above !== null) observer.observe(above);
    window.addEventListener('resize', measure);
    return () => {
      observer.disconnect();
      window.removeEventListener('resize', measure);
    };
  }, []);

  return (
    <div
      ref={boardRef}
      // Признак для `app-shell.tsx`: только по нему оболочка меняет свой нижний
      // край с общего хвоста страницы на хвост доски (`has-[[data-board]]`, UI-129).
      data-board=""
      style={
        { '--ui-board-height': `calc(100dvh - ${top}px - var(--ui-board-tail))` } as CSSProperties
      }
      className="pin-scope flex flex-col fold:h-(--ui-board-height)"
    >
      {/*
       * `items-stretch`, а не Tailwind по умолчанию (`items-start` стояло здесь до
       * UI-67): столбец — это рамка ровно по числу карточек, флекс-ряд без выравнивания
       * растягивает высоту ряда до самого длинного столбца, но не растягивает в неё
       * остальные. Короткий столбец рядом с длинным гас пустотой уже на второй
       * карточке, ничем не отличимой от пустоты соседа, — доска читалась как один
       * общий поток в шести колонках, а не как шесть отдельных отборов по статусу.
       * `items-stretch` растягивает саму секцию столбца (заливку и границу) до высоты
       * ряда; карточки внутри неё по-прежнему пакуются сверху (`flex-col`, без
       * `flex-grow` на списке), поэтому лишняя высота уходит в пустое место под
       * последней карточкой, а не растягивает сами карточки.
       *
       * `fold:flex-1` при `fold:min-h-0` — ряд забирает остаток доски под собой,
       * а `min-h-0` снимает с него пол по содержимому, иначе прокручиваться было бы
       * нечему. Обе утилиты стоят от точки остановки: ниже неё у доски нет своей
       * высоты, и `flex-1` без неё схлопнул бы ряд в ноль.
       */}
      <div className="flex items-stretch gap-3 overflow-x-auto pb-2 fold:min-h-0 fold:flex-1">
        {TASK_STATUSES.map((status) => (
          <BoardColumn
            key={status}
            status={status}
            params={params}
            explained={explained}
            open={!collapsed.includes(status)}
            onToggle={onToggle}
          />
        ))}
      </div>
    </div>
  );
}

interface BoardColumnProps {
  status: TaskStatus;
  params: TaskListParams;
  explained: boolean;
  open: boolean;
  onToggle: (status: TaskStatus, open: boolean) => void;
}

/**
 * Столбец доски: заголовок со счётчиком и карточки под ним.
 *
 * Свой компонент, а не кусок перебора, потому что читает он сам: свой отбор, свой
 * курсор, своё число. Здесь же живёт раскрытие, которое держит карточки до конца
 * выхода (`useExitHold`), — хук в теле перебора не живёт.
 */
function BoardColumn({ status, params, explained, open, onToggle }: BoardColumnProps) {
  const reveal = useExitHold(open);
  const { t } = useTranslation('tasks');
  const area = useRef<HTMLElement>(null);
  // Число в заголовке идёт за языком, как и всякое число в интерфейсе (UI-79).
  const { language } = useLanguage();

  /*
   * Раскрытый столбец читает карточки страницами, свёрнутый — только своё число.
   * Свёрнуты по умолчанию двое (`done`, `cancelled`), и вычитывать их выдачу ради
   * одного числа в заголовке значило бы читать сотню строк, которых никто не просил.
   */
  const pages = useInfiniteQuery({ ...tasksColumnQueryOptions(status, params), enabled: open });
  const counted = useQuery({
    ...tasksTotalQueryOptions({ ...params, status: [status] }),
    enabled: !open,
  });

  const tasks = pages.data?.pages.flatMap((page) => page.items) ?? [];
  /*
   * Число в заголовке — от бэкенда, а не от длины прочитанного: `meta.total` считает
   * всю выдачу по отбору (TRK-41). Раскрытому столбцу оно приезжает вместе с первой
   * страницей, свёрнутому — отдельным запросом; прочитанное остаётся в кэше, поэтому
   * свёртывание уже читанного столбца числа не роняет.
   */
  const total = pages.data?.pages[0]?.meta?.total ?? counted.data ?? null;
  const empty = total === 0 || (pages.data !== undefined && tasks.length === 0);

  const failed = pages.error !== null && pages.error !== undefined;

  /*
   * Сторож в конце столбца зовёт следующую страницу. Он снимается на время запроса
   * и после отказа: оставленный, он позвал бы снова в том же кадре, в котором вернулся
   * отказ, — и это был бы цикл запросов, которого задача запрещает. Возвращает сторожа
   * удачный повтор по кнопке.
   */
  const end = useEndReach({
    area,
    enabled: open && pages.hasNextPage && !pages.isFetchingNextPage && !failed,
    onReach: () => void pages.fetchNextPage(),
  });

  /*
   * Виден ли конец столбца прямо сейчас — от этого и только от этого зависит знак
   * края внизу (UI-90). Тот же сторожевой приём, что у дочитывания, и тот же выбор
   * корня; сторож у них разный — этому положено стоять ниже состояния дочитывания.
   */
  const edge = useBeyondEdge({ area });

  /**
   * Состояние дочитывания. Отдельно от состояния столбца: «читаем» здесь значит
   * «читаем следующую страницу», а повтор после отказа зовёт её же, а не перечитывает
   * весь столбец с начала.
   */
  const more: QueryLike = {
    isPending: pages.isFetchingNextPage,
    isFetching: pages.isFetchingNextPage,
    error: explained || pages.data === undefined ? null : pages.error,
    refetch: () => void pages.fetchNextPage(),
  };

  return (
    <section
      ref={area}
      /*
       * `relative` — точка отсчёта для абсолютных потомков, прежде всего для
       * `sr-only` спанов, которыми знак статуса называет свой род диктору.
       * Абсолютного потомка обрезает прокручиваемый предок только тогда, когда
       * тот стоит в его цепочке содержащих блоков; пока столбец позиционирован
       * не был, содержащим блоком таких спанов оказывалось окно: доска их не
       * обрезала, и они растягивали документ — с шестым столбцом (UI-40)
       * страница на 1440 px поехала вбок на 103 px вместе с боковой панелью
       * и шапкой. `contain: paint` чинит симптом, но заводит контекст наложения
       * и обрезает тени, поэтому лечится цепочка.
       *
       * Ширина задана и не делится между столбцами: при `flex: 1 1 16rem`
       * раскрытие одного столбца сужало все остальные (замерено: 265 → 190 px),
       * и карточки в столбце, который человек в этот момент читал, переносили
       * текст по-другому. Не влезли — ряд столбцов прокручивается вбок.
       *
       * Промежутка `gap-2` между заголовком и карточками нет: он стоит на самих
       * карточках (`mt-2`) и потому уезжает вместе с местом. Промежуток между
       * соседями держался бы, пока стоит сосед, и свёртывание кончалось бы
       * скачком в восемь пикселей.
       *
       * `fold:overflow-y-auto` — своя прокрутка столбца (UI-68): карточки уезжают
       * внутри него, соседние столбцы и страница при этом стоят. Она же корень
       * наблюдателя, который дочитывает столбец по мере прокрутки: ниже точки
       * остановки прокрутки у столбца нет вовсе, и корнем там становится окно
       * (`useEndReach`, `scrollingArea`). Отдельного `tabIndex` под прокрутку
       * не нужно — кнопка свёртывания стоит внутри самого прокручиваемого столбца,
       * и с фокусом на ней он ходит стрелками и `PageDown`.
       */
      className={cn(
        'relative flex w-(--ui-board-column) shrink-0 basis-(--ui-board-column) flex-col rounded-control border border-line bg-sunken fold:min-h-0 fold:overflow-y-auto',
        /*
         * Свёрнутый и пустой столбец остаётся столбцом той же ширины (решение
         * Д19): раньше он превращался в пилюлю по ширине содержимого, и ряд
         * читался как набор разных вещей — `backlog 0`, `done 32`, `cancelled 0`.
         * Гаснет он не прозрачностью, а отсутствием заливки: `opacity` смешивает
         * текст с фоном и роняет контраст (`docs/notes/ui.md`).
         *
         * Считается это по тому, держат ли карточки, а не по самому раскрытию:
         * пока свёртывание едет, столбец ещё со своими карточками, и рамка,
         * ставшая пунктирной в первом кадре, объявила бы его пустым раньше времени.
         *
         * С UI-67 высота у всех шести столбцов одна — по самому длинному
         * (`items-stretch` на ряду), — и различие полного, пустого и свёрнутого
         * столбца держится **только** на этой паре классов: заливка есть или нет,
         * граница сплошная или пунктирная. Высота им общая и раньше не давала
         * ничего, кроме случайного совпадения на коротких столбцах; теперь она
         * не даёт и его.
         */
        (!reveal.held || empty) && 'border-dashed bg-transparent',
      )}
      aria-label={status}
    >
      {/*
       * Боковые поля столбца носит эта прослойка, а не сам столбец, — и это не вкус,
       * а причина дефекта UI-117.
       *
       * Столбец с `fold` — контейнер прокрутки, и область прокрутки у такого считается
       * не по содержимому, а по правилу: объединение его padding-бокса с рамками
       * потомков, **и к концу этого объединения прибавляется своё поле контейнера**
       * (`css-overflow-3`, scrollable overflow region). Заголовок с `-mx-3` растянут
       * ровно на весь padding-бокс, то есть достаёт до правого края объединения, —
       * значит по спецификации область прокрутки шире столбца ровно на его `px-3`.
       * Safari 18.6 так и считает: у владельца все шесть столбцов дают `clientWidth`
       * 246 при `scrollWidth` 258 (`UI-117`), и вторая ось рядом с `overflow-y: auto`
       * вычисляется в `auto` — отсюда горизонтальная полоса у каждого столбца.
       * Chromium 151 и WebKit 26.5 прибавки не делают (замерено и на живой странице,
       * и на синтетике, `UI-117#5`), поэтому весь сквозной набор дефекта не видел.
       *
       * Лечится не полоса, а причина: у контейнера прокрутки боковых полей больше нет
       * вовсе — прибавлять нечего ни одному движку, ни нынешнему, ни будущему.
       * Поля переехали на прослойку, которая сама ничего не прокручивает, и всё, что
       * стоит внутри, стоит там же, где стояло: содержимое — в 222 px между полями,
       * `-mx-3` заголовка и нижней кромки достаёт до тех же краёв (теперь до краёв
       * прослойки, а она ровно во всю ширину области прокрутки). Раскладка в покое
       * не меняется ни на пиксель.
       *
       * `overflow-x: clip` на столбец отвергнут замером, а не вкусом: рядом с
       * `overflow-y: auto` он вычисляется в `hidden` (проверено в обоих движках),
       * а `hidden` области прокрутки не отменяет — `scrollWidth` остался бы 258,
       * просто полосу никто бы не нарисовал. Это спрятало бы и будущее настоящее
       * переполнение содержимым, которое ловит сторож в наборе (UI-115).
       *
       * `shrink-0` обязателен: столбец — флекс-колонка с заданной высотой, и без него
       * прослойка сжалась бы до высоты столбца, а содержимое вылезло бы из неё —
       * прокручивать было бы нечего, а липкая нижняя кромка считала бы свой предел
       * от сжатой прослойки. С ним высота прослойки — по содержимому, как была
       * высота содержимого самого столбца.
       */}
      <div className="flex shrink-0 flex-col px-3">
        {/*
         * Заголовок виден на любой глубине прокрутки: знак статуса и число остаются на
         * экране, а не уезжают вместе с карточками. Держит его у верха разное — смотря по
         * тому, что прокручивается в ветке ширины.
         *
         * С точки остановки `fold` — липкость (UI-69). Столбец прокручивается сам
         * (`fold:overflow-y-auto`, UI-68), он же ближайший порт прокрутки заголовка, и
         * `sticky top-0` держит заголовок у верха столбца.
         *
         * Ниже `fold` — прижим к окну (UI-94, `pin-top` в `shared/styles/theme.css`).
         * Прокручивается там страница, а липнуть заголовку не к чему: его порт прокрутки
         * не окно, а ряд столбцов — `overflow-x-auto` делает ряд прокручиваемым по обеим
         * осям, а по вертикали он не едет (замерено: страница уехала на 270 px, заголовок
         * вместе со своим столбцом, `top` −23 при `top` столбца −24; `docs/notes/ui.md`,
         * «Ниже точки остановки заголовку столбца липнуть не к чему»). Прижим считается
         * от шкалы доски (`pin-scope`), которая стоит снаружи ряда и потому меряет окно:
         * заголовок сдвигается ровно на столько, на сколько верх доски ушёл за верх окна.
         * Разметка та же — заголовок остаётся первым узлом своего столбца, едет вбок вместе
         * с ним и читается диктором там же. Другие ходы отвергнуты замером (`UI-94#5`):
         * `clip` у ряда отнимает пять столбцов из шести, своя прокрутка столбца оставляет
         * карточкам на телефоне 227–379 px вместо 529–625, а перелистывание столбцов
         * порта прокрутки не меняет. Браузер без шкал прокрутки (Firefox) прижима не
         * знает: там заголовок уезжает, как уезжал до UI-94.
         *
         * `top-0` у липкого без всякой поправки: над заголовком не стоит ничего — ни шапки
         * приложения (её нет после UI-38), ни своей полосы у доски. `--ui-header`,
         * оставшийся от снесённой оболочки, уже однажды оставил под липким элементом
         * щель (`docs/notes/ui.md`, «Липкое липнет к тому, что под ним»).
         *
         * Три решения, каждое обязательно, — те же, что у шапки таблицы:
         *
         * 1. Полей по вертикали нет вовсе — ни у столбца, ни у прослойки (`px-3`
         *    вместо `p-3`; с UI-117 эти боковые поля носит прослойка), а свои
         *    двенадцать пикселей заголовок носит сам (`pt-3`); нижние носит сторож конца
         *    (UI-90). Липкое внутри прокручиваемого столбца считается от его
         *    **содержимого**, а не от рамки: пока верхнее поле стояло на секции, `top-0`
         *    прижимал заголовок к нижнему краю поля — на тринадцатом пикселе от рамки
         *    вместо первого (замерено: `top` заголовка 133 при `top` столбца 120), —
         *    и над ним оставалась щель в двенадцать пикселей, сквозь которую ехали
         *    карточки. Отрицательное поле заголовку не помогало: `sticky` возвращал его
         *    обратно вниз, к своей границе. `-mx-3` при своих `px-3` остаётся — вбок
         *    заголовок обязан доставать до рамки, чтобы карточка не просвечивала краем;
         *    отсчитываются эти двенадцать пикселей от полей прослойки (UI-117), и края
         *    у неё те же, что были у столбца.
         *    Прижиму поле безразлично: где заголовок стоит в доске, там он и прижат, —
         *    у рамки столбца, то есть в пикселе от верха окна.
         * 2. Свой фон: у прилипшего и прижатого элемента фона нет, и карточки
         *    просвечивают сквозь него. Фон тот же, что у столбца (`bg-sunken`), —
         *    заголовок обязан читаться продолжением своего столбца, а не плашкой поверх
         *    него. Тень — тоже в обеих ветках: прижатый так же лежит поверх проезжающих
         *    карточек, как липкий.
         * 3. `z-2`, а не `z-1`, и в обеих ветках: карточка позиционирована (растянутая
         *    ссылка), и позиционированное рисуется поверх липкого по порядку разметки,
         *    а карточка в разметке ниже. Единицы мало: внутри карточки свои поднятые
         *    узлы — название и исполнитель стоят `relative z-1` над растяжкой
         *    (`entities/task/ui/task-card.tsx`), и при равном `z-index` побеждает опять
         *    тот, кто ниже, — то есть проезжающая карточка поверх шапки. Ниже `fold`
         *    позиционирования у заголовка нет, и оно не нужно: он элемент флекс-колонки
         *    столбца, а у такого `z-index` действует и без него (замерено на прижатой шапке:
         *    с `z-2` она сверху в 10 точках из 10, без него — в нуле).
         *
         * Гаснет заголовок вместе со столбцом: свёрнутому и пустому фон и тень не нужны
         * — под ним нечему проезжать, а заливка сделала бы из пунктирной рамки плашку.
         */}
        <h2
          className={cn(
            'z-2 -mx-3 rounded-t-control px-3 pt-3 pb-2 text-body max-fold:pin-top fold:sticky fold:top-0',
            !reveal.held || empty ? 'bg-transparent' : 'bg-sunken shadow-sticky',
          )}
        >
          <button
            type="button"
            /*
             * Знак раскрытия рисуется псевдоэлементом, а не узлом разметки: это
             * оформление кнопки, и диктору его читать незачем — состояние он берёт
             * из `aria-expanded`. Границы и заливки у кнопки нет вовсе, но названы
             * они явно: без этого браузер рисует свои `ButtonBorder` и `ButtonFace`.
             */
            className="flex w-full items-baseline gap-2 border-none border-current bg-transparent p-0 text-left text-text before:text-muted before:content-['▾'] aria-[expanded=false]:before:content-['▸']"
            aria-expanded={open}
            onClick={() => onToggle(status, !open)}
          >
            {/* Тот же знак, что в списке и на карточке: где бы человек ни
              увидел `in_progress`, это один и тот же полукруг (решение Д20). */}
            <StatusMark status={status} className="font-mono" />
            <span className="text-meta whitespace-nowrap text-muted">
              {/* Сколько задач в статусе, говорит бэкенд. Пока не сказал, врать нечем:
                раскрытый столбец говорит «столько-то из ?» о прочитанном, свёрнутый
                не говорит и этого — он не читал ничего. */}
              {total === null
                ? open
                  ? t('board.ofUnknown', { count: tasks.length })
                  : t('board.unknown')
                : formatNumber(total, language)}
            </span>
          </button>
        </h2>

        {reveal.held ? (
          <Reveal hold={reveal}>
            {pages.data === undefined ? (
              /*
               * Первого ответа ещё нет — или не будет вовсе. И то и другое сказано
               * словами, а отказ ещё и с кнопкой повтора: молчащий столбец неотличим
               * от пустого. Молчит он ровно в одном случае — когда тот же отказ уже
               * объяснён формой отбора у поля запроса.
               */
              <div className="mt-2">
                {explained ? null : <QueryState query={pages} loading={t('board.reading')} />}
              </div>
            ) : tasks.length === 0 ? (
              <p className="mt-2 text-meta text-muted italic">{t('board.empty')}</p>
            ) : (
              <>
                <ul className="mt-2 flex list-none flex-col gap-2 p-0">
                  {tasks.map((task) => (
                    <li key={task.key}>
                      <TaskCard task={task} />
                    </li>
                  ))}
                </ul>

                {/*
                 * Сторож конца: узел под последней карточкой. Дочитывание начинается,
                 * когда до него остаётся четверть высоты столбца, — то есть по мере
                 * прокрутки, а не по нажатию. Диктору узел не нужен: то же самое ему
                 * скажет состояние под ним.
                 *
                 * `h-px`, а не пустая высота: узел нулевой высоты наблюдатель считает
                 * видимым и внутри обрезанного места, поэтому раскрытие столбца читало
                 * страницу за страницей, пока едет движение (замерено: 30 карточек
                 * вместо 10). У узла с высотой обрезание отнимает всё пересечение,
                 * и движение остаётся движением, а не поводом читать.
                 */}
                <div ref={end} className="h-px" aria-hidden="true" />

                {more.isPending || more.error !== null ? (
                  <div className="mt-2">
                    <QueryState query={more} loading={t('board.readingMore')} compact />
                  </div>
                ) : null}
              </>
            )}
          </Reveal>
        ) : null}

        {/*
         * Сторож конца — он же нижнее поле столбца, и это не экономия узла, а условие.
         * Липкое у нижнего края заперто в содержимом так же, как липкое у верхнего:
         * `sticky bottom-0` не выходит за содержащий блок, а поле лежит **за** ним —
         * знак вставал бы на тринадцатом пикселе от рамки вместо первого (замерено).
         * Поэтому `pb-3` снято с секции, и те же двенадцать пикселей носит сторож
         * (`h-3`): высота содержимого прежняя, а знак достаёт до рамки.
         *
         * Стоит он ниже всего, что рисует столбец, — ниже состояния дочитывания тоже.
         * Выше он значил бы «конец виден» там, где видно строку „Читаем ещё…“, под
         * которой приедут ещё карточки.
         *
         * `shrink-0` обязателен: столбец — флекс-колонка, и переполненный ряд сжимает
         * элементы без своего содержимого в ноль. Сжатый сторож унёс бы с собой и нижнее
         * поле, и высоту содержимого — то есть само условие, по которому он стережёт.
         */}
        <div ref={edge.end} className="h-3 shrink-0" aria-hidden="true" />

        {/*
         * Знак края (UI-90): по столбцу в покое видно, кончился он или за краем есть ещё
         * карточки. Сказать это было нечем — полосу прокрутки macOS показывает наложением
         * на время жеста, а страница на доске не прокручивается вовсе (UI-68), и столбец
         * с сорока пятью карточками выглядел так же, как столбец с четырьмя.
         *
         * Знак — не полоса прокрутки и не счётчик, а край: полоска в высоту нижнего поля
         * столбца, где цвет границы (`--color-line-strong`) проступает из прозрачности
         * и снова тает в неё, симметрично, серединой на середине полоски (`bg-linear-to-t
         * from-transparent via-line-strong to-transparent`). Карточка под ней обрезана
         * ровно по краю, а не «кончилась», и это читается без подписи.
         *
         * Затухание с обеих сторон, а не сплошная заливка с линией и тенью, как было до
         * UI-145 (`shadow-edge`, снят, `docs/notes/ui.md`): решение отвечает на два разных
         * слова владельца, снявшего Safari 18.6 (UI-145#14).
         *
         * «Съехал» — прежний знак доставал ровно до внутренней ширины столбца, а не до
         * его рамки: своя полоса прокрутки (UI-116) занимает место внутри области
         * прокрутки, и знак, живущий в той же области, кончается вместе с ней — на
         * `--ui-scrollbar` раньше рамки (та же причина, что у горизонтального
         * переполнения UI-117, только по вертикальной оси знака). Это не ошибка счёта —
         * числа сошлись у обоих концов (UI-145#14) — а свойство любого узла внутри
         * `overflow`: дальше вправо знаку хода нет, это место навсегда занято браузерной
         * полосой. Раздвинуть край, значит, нельзя — можно только не давать ему резкой
         * границы, которую есть с чем сравнивать. Прежняя жёсткая линия у верхнего края
         * знака (`0 -1px 0 var(--t-line-strong)`) была и такой границей: заметная на глаз
         * величина, на которую она не дотягивала до рамки, читалась как сдвиг. Затухание
         * с обеих сторон её не оставляет: пиковая яркость — в середине полоски, обе её
         * границы (вертикальные, по бокам знака, и горизонтальные, сверху и снизу) уже
         * прозрачны там, где раньше стояла жёсткая линия.
         *
         * «Режет» — та же прежняя линия и тень над ней ложились на нижние двенадцать
         * пикселей карточки резким прямоугольником с чёткой верхней гранью, и на значке
         * замка (у карточки с открытым вопросом) это читалось как срез, а не как край.
         * Симметричное затухание того же цвета не даёт задать вопрос «где кончается
         * знак»: у него нет строки пикселей, в которой он был бы, а рядом — не был.
         *
         * Контраст держит выбор цвета, не сила: `--color-sunken` (был бы логичен как «свой
         * цвет столбца, тающий в ничто») даёт с заливкой карточки только 1.14 — тот же
         * порядок, что у слабой линии `--t-line`, которую заменили на сильную по той же
         * причине (см. соседний комментарий у прежнего `--t-edge`, `tokens.css`). У
         * `--color-line-strong` в пике (50%, `via-line-strong` без затухания в самой
         * точке) — 1.47/1.29 (карточка/столбец) в светлой теме и 1.58/1.45 в тёмной:
         * тот же порядок, что держал прежний знак (порог тестов — 1.25, `board.spec.ts`).
         *
         * Три решения, каждое обязательно:
         *
         * 1. **Знак стоит в разметке, а не в фоне области.** Тот же край рисуется вовсе
         *    без скрипта — фоном с `background-attachment: local`, — но фон рисуется
         *    **под** содержимым, а карточка непрозрачна (`bg-surface`): тень была бы видна
         *    только в промежутках между карточками. Знаку положено лежать поверх, поэтому
         *    это узел. Липкий: `sticky bottom-0` прижимает его к нижней рамке ровно тогда,
         *    когда содержимое уходит за неё, — то же условие, что стережёт наблюдатель,
         *    и другого места у знака не бывает по построению.
         * 2. **Высоты он не занимает.** `-mt-3` при `h-3` даёт вклад в высоту содержимого
         *    ноль, а стоит знак ровно в той полосе, где содержимое бывает только на
         *    прокрутке, — поверх нижнего поля, которое носит сторож. Отнимать высоту
         *    у карточек ему нечем: её и так остаётся 674 px на окне 900 (UI-68#10).
         *    `shrink-0` — по той же причине, что у сторожа: без него переполненный
         *    столбец сжимал бы знак в ноль, и затуханию не осталось бы высоты, чтобы
         *    затухать (замерено: высота 0 при заказанных двенадцати).
         * 3. **`z-2` и `pointer-events-none`.** Поднят знак выше карточки по той же
         *    причине, что и шапка: внутри карточки свои `relative z-1`. А нажатия сквозь
         *    него проходят — под ним лежат последние двенадцать пикселей карточки-ссылки,
         *    и съесть их знак не вправе.
         *
         * Показывается он по наблюдателю, а не по `scrollTop`: работы на кадр прокрутки
         * знак не стоит вовсе. Оттуда же его честность — у столбца, который поместился
         * целиком, конец виден всегда, и знака нет ни кадра; ниже точки остановки, где
         * своей прокрутки у столбца нет, наблюдателя нет вместе со знаком.
         *
         * Верхнего края знак не трогает: там стоит липкая шапка со своей тенью (UI-69),
         * и второй знак дрался бы с ней за то же место. «Есть ли что-то выше» человек
         * и так знает — выше он уехал сам.
         */}
        {edge.beyond ? (
          <div
            className="pointer-events-none sticky bottom-0 z-2 -mx-3 -mt-3 h-3 shrink-0 bg-linear-to-t from-transparent via-line-strong to-transparent"
            data-edge="beyond"
            aria-hidden="true"
          />
        ) : null}
      </div>
    </section>
  );
}
