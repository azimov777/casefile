import { useTranslation } from 'react-i18next';
import { TASK_COLUMNS, TaskRow, type Task } from '@/entities/task';

interface TasksTableProps {
  tasks: Task[];
  /** Показанное устарело: идёт запрос или последний был отклонён. */
  stale: boolean;
}

/**
 * Ширины колонок заданы здесь и не зависят от содержимого: при раскладке по
 * содержимому колонка расширялась под самое длинное значение и отнимала ширину
 * у названия, а при листании сетка перекраивалась от страницы к странице. Название
 * забирает всё, что осталось, — и после снятия тегов (UI-41) это на 176 px больше.
 */
const WIDTHS = [
  'w-20', // Ключ — 80 px
  'w-auto', // Название — всё, что осталось
  'w-30', // Статус — 120 px
  'w-26', // Исполнитель — 104 px
  'w-24', // Приоритет — 96 px, было 94.8 по содержимому
  'w-24', // Признаки — 96 px: три знака с числами
  'w-26', // Активность — 104 px
];

/**
 * Таблица списка. Заголовки берутся у представления строки: порядок ячеек и порядок
 * столбцов обязаны совпадать, и держать их в двух местах значило бы однажды разойтись.
 *
 * **Обрезание заменено прокруткой.** `overflow-x: clip` прятал за правым краем статус,
 * приоритет и признаки: на 390 px из восьми колонок читались две, и добраться до
 * остальных было нечем. Теперь узкий экран прокручивает таблицу вбок внутри её рамки,
 * а страница вширь не едет.
 *
 * Ценой этого уходит липкая шапка на узком экране: `overflow-x: auto` делает обёртку
 * прокручиваемым предком, и шапка прилипает к ней, а не к окну (`docs/notes/ui.md`,
 * «Липкую шапку таблицы ломает `overflow` у её обёртки»). На широком экране, где
 * прокручивать нечего, обёртка остаётся `clip`, и шапка держится у верха окна — этого
 * требует UI-12, и там же список бывает длинным.
 *
 * Прокручиваемая область обязана быть достижима с клавиатуры: без `tabIndex` до её
 * содержимого не добраться ничем, кроме мыши, и это нарушение ловит `axe`
 * (`scrollable-region-focusable`).
 */
export function TasksTable({ tasks, stale }: TasksTableProps) {
  const { t } = useTranslation('tasks');
  const { t: brick } = useTranslation('ui');

  return (
    <div
      role="region"
      aria-label={t('table.label')}
      tabIndex={0}
      /*
       * `relative` здесь не украшение и не задел на будущее: без позиционированной
       * рамки прокрутка вбок остаётся внутри, а **ширина документа** всё равно растёт
       * на ширину таблицы — на 320 px документ становится 789 px и страница едет
       * вширь целиком. Проверено пробой в обоих движках; раньше то же самое держал
       * `relative` у `<tr>`, поставленный ради растяжки ссылки, и связь эта была
       * невидимой: растяжка ушла (UI-39) — и узкий экран сломался.
       */
      className="relative max-fold:overflow-x-auto fold:overflow-x-clip rounded-block border border-line bg-surface focus-visible:outline-2 focus-visible:-outline-offset-2 focus-visible:outline-focus"
    >
      {/*
       * `min-w-[49rem]` — наименьшая ширина, при которой читаются все семь колонок:
       * шесть заданных ширин дают 600 px (80 + 120 + 104 + 96 + 96 + 104), и названию
       * остаётся 184 px — та же строка текста, что и раньше. Ниже неё таблица не
       * сжимается, а прокручивается. Класс написан целиком, а не собран из кусков:
       * Tailwind ищет в исходниках готовые имена классов.
       */}
      <table
        className="w-full table-fixed border-collapse text-body max-fold:min-w-[49rem]"
        aria-busy={stale}
      >
        {/*
         * Подпись таблицы читается программой чтения с экрана, но места на экране не
         * занимает: то же число человек видит в строке управления, рядом с заголовком
         * страницы.
         */}
        <caption className="sr-only">{t('table.caption', { count: tasks.length })}</caption>
        <thead>
          <tr>
            {TASK_COLUMNS.map((column, index) => (
              <th
                key={column}
                scope="col"
                /*
                 * Шапка держится у верха окна на любой глубине прокрутки: последние
                 * строки длинного списка читаются с подписанными колонками, а не
                 * наугад. Фон обязателен — у прилипшей ячейки нет своего, и строки
                 * просвечивали бы сквозь заголовок; нижняя граница нарисована тенью,
                 * потому что граница ячейки при `border-collapse` уезжает с прокруткой.
                 */
                className={`sticky top-0 z-1 h-(--ui-row-head) bg-surface px-3 text-left align-middle text-label font-semibold tracking-caps text-faint uppercase shadow-sticky ${WIDTHS[index] ?? ''} ${index === TASK_COLUMNS.length - 1 ? 'text-right' : ''}`}
              >
                {brick(`task.columns.${column}`)}
              </th>
            ))}
          </tr>
        </thead>
        <tbody className={stale ? 'opacity-60' : undefined}>
          {tasks.map((task) => (
            <TaskRow key={task.key} task={task} />
          ))}
        </tbody>
      </table>
    </div>
  );
}
