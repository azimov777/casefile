import { useTranslation } from 'react-i18next';
import { TASK_COLUMNS, TaskRow, type Task } from '@/entities/task';

interface TasksTableProps {
  tasks: Task[];
  /** Показанное устарело: идёт запрос или последний был отклонён. */
  stale: boolean;
}

/**
 * Ширины колонок заданы здесь и не зависят от содержимого: при раскладке по
 * содержимому колонка расширялась под самое длинное значение и отнимала ширину
 * у названия, а при листании сетка перекраивалась от страницы к странице. Название
 * забирает всё, что осталось, — и после снятия тегов (UI-41) это на 176 px больше.
 */
const WIDTHS = [
  'w-20', // Ключ — 80 px
  'w-auto', // Название — всё, что осталось
  'w-30', // Статус — 120 px
  'w-26', // Исполнитель — 104 px
  'w-24', // Приоритет — 96 px, было 94.8 по содержимому
  'w-24', // Признаки — 96 px: знаки с числами
  'w-26', // Активность — 104 px
];

/**
 * Таблица списка. Заголовки берутся у представления строки: порядок ячеек и порядок
 * столбцов обязаны совпадать, и держать их в двух местах значило бы однажды разойтись.
 *
 * **Две раскладки одной разметки, и выбирает их место таблицы** (UI-134). Где места
 * хватает на все колонки (`--container-list`, он же `min-w-list`), это таблица с липкой
 * шапкой. Где не хватает — та же `<table>` с теми же `<tr>` и `<td>` раскладывается
 * блоками: строка становится карточкой (`TaskRow`, ветка `@max-list:`), шапка уходит
 * в `sr-only` и остаётся диктору. Отдельного «мобильного» списка рядом нет: вторая
 * разметка однажды показала бы на телефоне другой трекер.
 *
 * До UI-134 узкая ветка была прокруткой вбок внутри рамки (UI-39, UI-66, UI-91): на
 * 390 px читались ключ, обрезанное до пятнадцати знаков название и статус, а остальное
 * пряталось за 428 px прокрутки. Прокрутки больше нет ни на какой ширине, и вместе с ней
 * ушли роль «область», имя «таблица прокручивается вбок» и остановка табом у рамки.
 *
 * **Ветку выбирает место таблицы, а не ширина окна** — по той же причине, что и раньше:
 * место у таблицы отбирает боковая панель, которая появляется на точке остановки `fold`,
 * и медиазапрос по окну ошибался бы в полосе 44–63.5rem (UI-66). Порог спрашивается
 * запросом к контейнеру (`@container` у рамки).
 *
 * `overflow-x: clip`, а не `auto`, на обеих ветках: прокручивать нечего, а `auto` сделал
 * бы рамку прокручиваемым предком, и липкая шапка прилипала бы к ней, а не к окну
 * (`docs/notes/ui.md`, «Липкую шапку таблицы ломает `overflow` у её обёртки»). Обрезает
 * он только чужое, не помещённое в ячейку: длинное имя исполнителя в таблице.
 */
export function TasksTable({ tasks, stale }: TasksTableProps) {
  const { t } = useTranslation('tasks');
  const { t: brick } = useTranslation('ui');
  // Гнездо под плашку родителя — у всех строк, если родитель есть хоть у одной (UI-152).
  const parentSlot = tasks.some((task) => task.parent != null);

  return (
    /*
     * Рамка таблицы — она же контейнер запроса, и это не совпадение. Запрос к
     * контейнеру меряет его **содержимое**, то есть коробку без рамки, — а таблице
     * достаётся ровно она. Держи рамку ниже, и контейнер мерил бы коробку на две
     * рамочные линии шире места: в полосе шириной в эти два пикселя строка уже
     * оставалась бы строкой таблицы, не влезая в неё (UI-66).
     */
    <div className="@container rounded-block border border-line bg-surface">
      {/*
       * Скругление повторено здесь, а не только на рамке выше: `clip` обрезает
       * содержимое по своей коробке, и без него фон прилипшей шапки закрасил бы
       * скруглённые углы рамки квадратными.
       */}
      <div className="overflow-x-clip rounded-block">
        {/*
         * `min-w-list` — наименьшая ширина, при которой читаются все колонки: заданные
         * ширины дают 600 px (80 + 120 + 104 + 96 + 96 + 104), и названию остаётся
         * 184 px. Тем же именем назван порог ветки: ниже него таблица не сжимается, а
         * раскладывается карточками, и минимум ей там не нужен (`@max-list:min-w-0`).
         *
         * `block` у таблицы и тела — это и есть карточная ветка: строки перестают быть
         * рядами сетки таблицы и раскладываются каждая сама (`TaskRow`).
         */}
        <table
          className="w-full min-w-list table-fixed border-collapse text-body @max-list:block @max-list:min-w-0"
          aria-busy={stale}
        >
          {/*
           * Подпись таблицы читается программой чтения с экрана, но места на экране не
           * занимает: то же число человек видит рядом с заголовком страницы. Роль
           * таблицы, подписанные колонки и число строк на месте.
           */}
          <caption className="sr-only">{t('table.caption', { count: tasks.length })}</caption>
          {/*
           * В карточках шапка не нужна глазу — у каждого значения свой знак, — но
           * нужна диктору: по ней он называет колонку ячейки. Поэтому `sr-only`, а не
           * `hidden`.
           */}
          <thead className="@max-list:sr-only">
            <tr>
              {TASK_COLUMNS.map((column, index) => (
                <th
                  key={column}
                  scope="col"
                  /*
                   * Шапка держится у верха окна на любой глубине прокрутки: последние
                   * строки длинного списка читаются с подписанными колонками, а не
                   * наугад. Фон обязателен — у прилипшей ячейки нет своего, и строки
                   * просвечивали бы сквозь заголовок; нижняя граница нарисована тенью,
                   * потому что граница ячейки при `border-collapse` уезжает с прокруткой.
                   */
                  className={`sticky top-0 z-1 h-(--ui-row-head) bg-surface px-3 text-left align-middle text-label font-semibold tracking-caps text-faint uppercase shadow-sticky ${WIDTHS[index] ?? ''} ${index === TASK_COLUMNS.length - 1 ? 'text-right' : ''}`}
                >
                  {brick(`task.columns.${column}`)}
                </th>
              ))}
            </tr>
          </thead>
          <tbody className={stale ? 'opacity-60 @max-list:block' : '@max-list:block'}>
            {tasks.map((task) => (
              <TaskRow key={task.key} task={task} parentSlot={parentSlot} />
            ))}
          </tbody>
        </table>
      </div>
    </div>
  );
}
