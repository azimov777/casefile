import { useEffect, useRef, useState, type RefObject } from 'react';

/**
 * Конец содержимого: докрутили — позвать; не докрутили — сказать.
 *
 * Сторож в конце содержимого и наблюдатель пересечения над ним: пока сторож за краем
 * видимой части, ничего не происходит; показался — зовётся `onReach`. Ни таймеров,
 * ни обработчика прокрутки: обработчик считал бы геометрию на каждом кадре прокрутки,
 * а наблюдатель молчит, пока пересечение не изменилось.
 *
 * На том же стороже стоит второй хук, `useBeyondEdge`: он спрашивает не «докрутили ли
 * сейчас», а «видно ли конец» — тот же вопрос в покое. Оба живут в одном файле ради
 * одного `scrollingArea`: корень у них общий, и разойтись в выборе корня они не вправе.
 */

/**
 * Насколько раньше края спрашивать следующее: четверть высоты области.
 *
 * Не ноль — иначе человек упирается в дно и ждёт; но и не «экран вперёд»: цель задачи
 * в том, чтобы читать меньше, а не в том, чтобы читать то же самое по другому поводу.
 * Доля, а не пиксели: область бывает и столбцом доски, и окном телефона.
 */
const READ_AHEAD = '0px 0px 25% 0px';

interface EndReach {
  /**
   * Область, внутри которой едет содержимое, — если она прокручивается сама.
   * Наблюдателю она отдаётся корнем; когда область прокруткой не является,
   * корнем остаётся окно (см. `scrollingArea`).
   */
  area: RefObject<HTMLElement | null>;
  /**
   * Стеречь ли конец сейчас. Ложь снимает наблюдателя вовсе — это и запрет
   * («читать больше нечего», «прошлый ответ не дошёл»), и способ перевести
   * сторожа на новое содержимое: наблюдатель, поставленный заново, сразу говорит,
   * виден ли сторож, а оставленный молчит, пока пересечение не изменится.
   */
  enabled: boolean;
  onReach: () => void;
}

/**
 * Ставит сторожа в конец содержимого. Возвращает ссылку, которую вешают на пустой узел
 * после последнего элемента.
 */
export function useEndReach({
  area,
  enabled,
  onReach,
}: EndReach): (node: HTMLElement | null) => void {
  // Узел приходит состоянием, а не ссылкой: наблюдателя ставит эффект, а он обязан
  // проснуться, когда сторож появился в разметке, — на правку `ref.current` React
  // ничего не перерисовывает.
  const [end, setEnd] = useState<HTMLElement | null>(null);

  // Обработчик живёт в ссылке: он собирается заново на каждой отрисовке, и включи его
  // в зависимости эффекта — наблюдатель пересоздавался бы вместе с ним.
  const reach = useRef(onReach);
  useEffect(() => {
    reach.current = onReach;
  });

  useEffect(() => {
    if (!enabled || end === null) return;
    // В jsdom наблюдателя пересечения нет вовсе: без этого падает среда, а не поведение.
    if (typeof IntersectionObserver === 'undefined') return;

    let observer: IntersectionObserver | null = null;

    /*
     * Корень выбирается заново на каждом изменении размера окна: прокручиваемой
     * областью столбец доски становится по ширине окна (`fold`), а ниже неё
     * прокручивается страница, и корнем обязано быть окно (UI-68, UI-70#7).
     */
    const watch = () => {
      observer?.disconnect();
      observer = new IntersectionObserver(
        (entries) => {
          if (entries.some((entry) => entry.isIntersecting)) reach.current();
        },
        { root: scrollingArea(area.current), rootMargin: READ_AHEAD },
      );
      observer.observe(end);
    };

    watch();
    window.addEventListener('resize', watch);
    return () => {
      window.removeEventListener('resize', watch);
      observer?.disconnect();
    };
  }, [area, enabled, end]);

  return setEnd;
}

interface BeyondEdge {
  /**
   * Область, внутри которой едет содержимое. Спрашивать её о том, что за краем, имеет
   * смысл только тогда, когда она прокручивается сама: где прокрутки нет, за краем
   * ничего и не спрятано.
   */
  area: RefObject<HTMLElement | null>;
}

interface Edge {
  /** Есть ли за нижним краем области ещё содержимое. */
  beyond: boolean;
  /** Ссылка на сторожа: пустой узел в самом конце содержимого. */
  end: (node: HTMLElement | null) => void;
}

/**
 * Кончилось ли содержимое области — или за нижним краем есть ещё.
 *
 * Тот же сторож и тот же наблюдатель, что у дочитывания, но вопрос другой: не «пора
 * читать», а «что показывать в покое». Сторож виден — конец на экране, показывать
 * нечего; сторож за краем — за краем есть ещё, и это единственное состояние, в котором
 * знак края имеет право быть нарисован.
 *
 * Работы на кадр прокрутки здесь нет ни одной: наблюдатель молчит, пока пересечение
 * не изменилось, то есть говорит дважды на всю прокрутку столбца — когда конец ушёл
 * за край и когда вернулся. Обработчик прокрутки или замер `scrollTop` считали бы
 * то же самое шестьдесят раз в секунду.
 */
export function useBeyondEdge({ area }: BeyondEdge): Edge {
  // Узел приходит состоянием, а не ссылкой: наблюдателя ставит эффект, а он обязан
  // проснуться, когда сторож появился в разметке.
  const [end, setEnd] = useState<HTMLElement | null>(null);
  /*
   * Ложь до первого слова наблюдателя, и это не мелочь: знак, нарисованный до замера,
   * пообещал бы содержимое за краем там, где его нет, — ровно та ошибка, которую
   * чинили для рамки таблицы (UI-91). Промолчать лишний кадр дешевле, чем соврать.
   */
  const [beyond, setBeyond] = useState(false);

  useEffect(() => {
    if (end === null) return;
    // В jsdom наблюдателя пересечения нет вовсе: без этого падает среда, а не поведение.
    if (typeof IntersectionObserver === 'undefined') return;

    let observer: IntersectionObserver | null = null;

    /*
     * Корень выбирается заново на каждом изменении размера окна — по той же причине,
     * что и у дочитывания: прокручиваемой областью столбец доски становится по ширине
     * окна (UI-68).
     */
    const watch = () => {
      observer?.disconnect();
      observer = null;

      const root = scrollingArea(area.current);
      /*
       * Область не прокручивается — знака нет вовсе, и окно в корень здесь не годится:
       * «сторож ушёл за нижний край окна» это не «в столбце есть ещё карточки», а
       * «страница длинная». Знак по такому корню обещал бы прокрутку столбца, которой
       * ниже точки остановки у него нет.
       */
      if (root === null) {
        setBeyond(false);
        return;
      }

      observer = new IntersectionObserver(
        (entries) => {
          // Последняя запись, а не первая: за один проход наблюдатель отдаёт всю
          // очередь изменений, и верно только её окончание.
          const last = entries[entries.length - 1];
          if (last !== undefined) setBeyond(!last.isIntersecting);
        },
        { root },
      );
      observer.observe(end);
    };

    watch();
    window.addEventListener('resize', watch);
    return () => {
      window.removeEventListener('resize', watch);
      observer?.disconnect();
    };
  }, [area, end]);

  return { beyond, end: setEnd };
}

/**
 * Прокручивается ли область сама — и потому годится ли она в корни наблюдателя.
 *
 * Спрашивается у вычисленного стиля, а не у точки остановки числом: одно и то же
 * правило (`fold:overflow-y-auto`) написано в разметке, и второе его имя в скрипте
 * разошлось бы с ним молча. Не прокручивается — корнем становится окно (`null`).
 */
function scrollingArea(node: HTMLElement | null): HTMLElement | null {
  if (node === null) return null;

  const overflow = getComputedStyle(node).overflowY;
  return overflow === 'auto' || overflow === 'scroll' ? node : null;
}
