import { useEffect, useState, type ReactNode } from 'react';
import { cn, exitDurationMs, type ExitHold } from '@/shared/lib';

interface RevealProps {
  /**
   * Задержка размонтирования этого узла — `useExitHold` у родителя, целиком. Из неё
   * берутся два признака: `leaving` — узел уже убран из показа и доживает выход,
   * `entering` — появился в ответ на событие, а не стоял с самого начала (ложь — входа
   * нет вовсе: движение отвечает на событие, `CONCEPT.md`, 6, а открытая страница с уже
   * раскрытым местом — не событие). И ссылка: раскрытие ставит её на своё место, чтобы
   * задержка сняла узел, когда движения выхода кончились, а не по сроку снаружи
   * (UI-111). Приходит задержка целиком, а не парой признаков, — ссылку тогда
   * не забыть.
   */
  hold: ExitHold;
  children: ReactNode;
}

/**
 * Раскрытие в потоке вёрстки: содержимое приезжает вместе со своим местом.
 *
 * Двигаются строки сетки (`grid-template-rows: 0fr → 1fr`), а не `height` и не
 * `transform` (решение UI-59#12). `transform` не двигает **место**: соседнее
 * содержимое прыгнуло бы в первом же кадре, то есть дефект остался бы, а движение
 * объясняло бы не то. `height: auto` не интерполируется вовсе.
 *
 * Обёрток две, и обе обязательны. Внешняя — само место: строки сетки и, пока оно едет,
 * обрезание. Внутренняя — прослойка с содержимым и его прозрачностью. У элемента сетки
 * минимальный размер по содержимому, и без `min-h-0` на прослойке строка `0fr` встала бы
 * на высоте содержимого, а не на нуле.
 *
 * Обрезает место, а не прослойка (UI-112). Chrome считает долю `fr` дважды: высоту
 * месту даёт по содержимому (f·h), а строку считает ещё раз, от этой высоты (f·f·h).
 * Прослойка стоит в строке, и обрезай она — посреди хода было бы видно f²·h содержимого,
 * а соседи ниже уже сдвинуты на f·h: под обрезанным краем пустая полоса, у отбора списка
 * до 50 px на пятой части хода. Край места идёт ровно там же, где соседи.
 *
 * Обрезание делает место контейнером прокрутки, а у такого элемента флекса
 * автоматический минимальный размер — ноль. Переполненный столбец доски со своей
 * прокруткой держал бы место на своём остатке посреди хода, и оно добирало бы высоту
 * скачком в кадр, где обрезание снято (замерено: 191,6 px из 268,4 шесть кадров подряд).
 * Поэтому на то же время — `shrink-0`: в покое он ничего не меняет, минимум там снова
 * по содержимому. `overflow: clip` контейнером прокрутки не делает, но наблюдатель
 * пересечений смотрит сквозь него, а сторож дочитывания столбца живёт внутри места
 * и обязан быть обрезан, пока место едет (`pages/tasks/ui/tasks-board.tsx`).
 *
 * Вход берётся `@starting-style` (`starting:`), а не первым кадром из скрипта: браузер
 * сам знает начальное значение только что вставленного узла, а «поставить 0fr и на
 * следующем кадре 1fr» из React — это лишняя отрисовка и гонка с раскладкой. Начинать
 * есть что не всегда: узлу, стоявшему с самого начала, `starting:` не выдают вовсе,
 * иначе раскрытия въезжали бы на каждой загрузке страницы, ничему не отвечая.
 *
 * Прозрачность здесь не украшение: она прячет край обрезания, у которого содержимое
 * рубится на полустроке. В покое её нет — по концу движения единица (`UI-59#4`).
 *
 * Родитель обязан снимать узел сам, когда `useExitHold` перестал его держать: узнать
 * это отсюда нельзя, а в описи дела раскрытие живёт целой строкой таблицы, и лишним
 * узлом в разметке она быть не вправе. Когда перестать держать, задержка узнаёт по
 * движениям места, на которое раскрытие ставит её ссылку: оба движения выхода —
 * строки сетки и прозрачность — живут в его поддереве.
 */
export function Reveal({ hold, children }: RevealProps) {
  const { leaving, entering, ref } = hold;
  /*
   * Обрезание нужно ровно пока едет место. В покое его нет намеренно: содержимое
   * бывает шире своего места по замыслу — объяснение отказа разбора запроса наложено
   * на страницу и выходит за нижний край формы (`task-filters.tsx`), — и постоянное
   * `overflow: hidden` резало бы его вместе с движением.
   */
  const [settled, setSettled] = useState(!entering);
  const clipped = leaving || !settled;

  useEffect(() => {
    // Выход снова обрезает: место едет в ноль, и содержимое обязано уезжать вместе с ним.
    if (leaving) {
      setSettled(false);
      return;
    }
    if (settled) return;

    /*
     * Страховка на случай, если конца перехода не будет вовсе: `@starting-style`
     * знают Chrome 117, Safari 17.5 и Firefox 129, а в браузере старше вход просто
     * не поедет — и обрезание, снятое только по `transitionend`, осталось бы навсегда.
     * Срок вдвое длиннее движения, чтобы в живом браузере успевал сработать переход,
     * а не эта страховка: снятое раньше времени обрезание показало бы содержимое
     * за краем места на последних кадрах.
     */
    const timer = setTimeout(() => setSettled(true), exitDurationMs() * 2);
    return () => clearTimeout(timer);
  }, [leaving, settled]);

  return (
    <div
      ref={ref}
      // Опора для замеров: длительность и кривую снимают с этого узла, а слепок
      // вычисленных стилей минует обе обёртки, сличая то, что внутри них.
      data-reveal="place"
      className={cn(
        'grid transition-[grid-template-rows] duration-(--motion-fast)',
        clipped && 'shrink-0 overflow-hidden',
        leaving ? 'grid-rows-[0fr] ease-exit' : 'grid-rows-[1fr] ease-fast',
        !leaving && entering && 'starting:grid-rows-[0fr]',
      )}
      onTransitionEnd={(event) => {
        // Только своё движение: прозрачность внутренней обёртки всплывает сюда же.
        if (event.target !== event.currentTarget) return;
        if (event.propertyName !== 'grid-template-rows') return;
        if (!leaving) setSettled(true);
      }}
    >
      <div
        // Обрезаемое: прослойка, которую режет край места. Сама она не обрезает ничего.
        data-reveal="clip"
        className={cn(
          'min-h-0 transition-opacity duration-(--motion-fast)',
          leaving ? 'opacity-0 ease-exit' : 'opacity-100 ease-fast',
          !leaving && entering && 'starting:opacity-0',
        )}
      >
        {children}
      </div>
    </div>
  );
}
