/**
 * Шкала размеров элементов управления — одна на кнопку (`Button`) и переключатель вида
 * (`SegmentedNav`). Размер задаёт высоту и кегль вместе: элементы одного размера,
 * поставленные в строку, одной высоты и стоят вровень, с какими бы подписями они ни были.
 *
 * - `md` — обычная кнопка: формы, диалоги, действия блока.
 * - `sm` — плотная строка: липкая навигация задачи, верхняя полоса, действие в строке
 *   списка, кнопка в подписи блока.
 *
 * Высота — минимумом (`min-h-*`), а не значением: при увеличенном тексте подпись растит
 * элемент, а не вылезает из него (`docs/notes/ui.md`, «Высота полосы задаётся минимумом»).
 * Ширину, отступы и тон каждый элемент решает сам — шкала говорит только о строке.
 */
export type ControlSize = 'sm' | 'md';

export const controlSize: Record<ControlSize, string> = {
  sm: 'min-h-(--ui-control-sm) text-meta',
  md: 'min-h-(--ui-control) text-body',
};
