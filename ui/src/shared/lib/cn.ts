import { clsx, type ClassValue } from 'clsx';
import { extendTailwindMerge } from 'tailwind-merge';

/**
 * Шкалы `@theme` этого проекта — те, чьи имена `tailwind-merge` обязан знать поимённо.
 *
 * Ключ — пространство имён темы Tailwind 4 (`--text-*` → `text`), значение — имена
 * без приставки. Список обязан слово в слово совпадать с `shared/styles/theme.css`;
 * стережёт это `cn.test.ts`, а не память: шкала пополняется в одном файле, а знать
 * о ней должны два.
 *
 * Зачем это вообще нужно. Библиотека разбирает утилиту по виду имени, а не по нашему
 * замыслу: кеглем она считает то, что похоже на размер (`sm`, `[13px]`), а всё
 * остальное после `text-` — цветом. Наша шкала названа ролью (`text-mark`,
 * `text-meta`), под «размер» не подходит ни одним именем, и `cn('font-mono text-mark',
 * 'text-muted')` возвращал `font-mono text-muted`: библиотека видела спор двух цветов
 * и оставляла последний. Ошибка молчала — класс исчезал при сборке строки, а не при
 * сборке CSS, поэтому в собранном CSS его просто не было и искать было нечего.
 *
 * Та же природа у радиусов, теней, разрядки, плавности и появления: их имён библиотека
 * не знает вовсе, и класс от места вызова не перебивал свой — то есть `cn` не делала
 * ровно того, ради чего заведена.
 */
export const THEME_SCALES = {
  text: ['title', 'screen', 'body', 'meta', 'mark', 'label'],
  tracking: ['caps'],
  radius: ['mark', 'control', 'block', 'pill'],
  shadow: ['raised', 'sticky'],
  ease: ['fast', 'exit'],
  animate: ['appear', 'disappear', 'sheet-in', 'sheet-out', 'overlay-in', 'overlay-out'],
} as const;

const twMerge = extendTailwindMerge({
  extend: { theme: THEME_SCALES },
  override: {
    /*
     * У чужой шкалы кегль несёт с собой высоту строки (`text-sm` печатает и
     * `line-height`), поэтому библиотека по умолчанию считает, что `font-size`
     * отменяет `leading-*`, названный левее. У нашей шкалы это неправда: пары
     * `--text-*--line-height` в `@theme` нет ни одной, и Tailwind печатает голый
     * `.text-body{font-size:var(--text-body)}`.
     *
     * Оставить правило значило бы завести на месте вылеченной потери такую же новую:
     * `<Button className="px-2 py-1 text-meta">` собирает `cn` из основы кнопки
     * (`text-body … leading-[1.2]`) и внешнего кегля, и высота строки уезжала бы
     * молча — потому что кегль стоит правее.
     *
     * Приставочная форма (`text-body/6`) высоту как раз задаёт, и её правило —
     * `conflictingClassGroupModifiers` — оставлено умолчанием намеренно.
     */
    conflictingClassGroups: { 'font-size': [] },
  },
});

/**
 * Склеивает классы утилит, оставляя из конфликтующих последний.
 *
 * Нужна ровно потому, что утилиты одного свойства не переопределяют друг друга
 * порядком в атрибуте: `px-4 px-2` даст тот из них, который стоит позже в
 * собранном CSS, а не в разметке. `twMerge` решает это по имени свойства,
 * поэтому класс, переданный местом вызова, действительно перебивает свой.
 *
 * Имена свойств библиотека берёт не только из своих умолчаний, но и из `THEME_SCALES`:
 * без них наша шкала кегля молча проигрывала бы цвету.
 */
export function cn(...classes: ClassValue[]): string {
  return twMerge(clsx(classes));
}
