import { clsx, type ClassValue } from 'clsx';
import { twMerge } from 'tailwind-merge';

/**
 * Склеивает классы утилит, оставляя из конфликтующих последний.
 *
 * Нужна ровно потому, что утилиты одного свойства не переопределяют друг друга
 * порядком в атрибуте: `px-4 px-2` даст тот из них, который стоит позже в
 * собранном CSS, а не в разметке. `twMerge` решает это по имени свойства,
 * поэтому класс, переданный местом вызова, действительно перебивает свой.
 */
export function cn(...classes: ClassValue[]): string {
  return twMerge(clsx(classes));
}
