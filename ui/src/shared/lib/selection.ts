import type { MouseEvent } from 'react';

/**
 * Отменяет переход по ссылке, если человек в этот момент выделял текст.
 *
 * Нужно там, где ссылка растянута на всю строку или карточку: протяжка мышью по
 * тексту заканчивается отпусканием кнопки внутри ссылки, и браузер считает это
 * кликом. Человек, выделивший название задачи, чтобы его скопировать, вместо этого
 * уезжал бы в саму задачу — и терял выделение вместе со страницей.
 *
 * Отменяется только переход и только по левой кнопке: `cmd`-клик, средняя кнопка
 * и «открыть в новой вкладке» выделения не создают и сюда не попадают. Переход
 * по-прежнему делает браузер по настоящей ссылке, а не наш обработчик.
 */
export function skipClickWhileSelecting(event: MouseEvent<HTMLElement>): void {
  const selected = window.getSelection()?.toString() ?? '';
  if (selected !== '') event.preventDefault();
}
