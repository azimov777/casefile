import { useRef } from 'react';

/**
 * Ключ повтора, привязанный к самому запросу.
 *
 * Зачем: повтор оборвавшейся отправки обязан идти с **тем же** `Idempotency-Key` —
 * иначе бэкенд заведёт второго участника, второй токен или второй проект, о котором
 * человек не узнает. И наоборот: тот же ключ с **другим** запросом бэкенд отвергает
 * (`409 idempotency_key_reused`), поэтому исправленное поле обязано получить новый
 * ключ, а не тащить прежний.
 *
 * Отсюда отпечаток: ключ живёт, пока живёт запрос, к которому он выдан.
 *
 * Почему не рядом с черновиком в `sessionStorage`, как у формы записи в дело
 * (`docs/notes/api.md`): повтор выпуска токена с тем же ключом сутки отдаёт **тот же
 * секрет**, то есть ключ равносилен самому секрету. Пережить вкладку он не должен —
 * и не переживает: память и только память. Окна проекта (`features/manage-project`)
 * берут его же: их ключ жить дольше окна тоже не обязан.
 */
export function useOnceKey<TInput>() {
  const kept = useRef<{ fingerprint: string; key: string } | null>(null);

  return {
    /** Ключ для этого запроса: прежний, если запрос тот же, и новый, если другой. */
    keyFor(input: TInput): string {
      const fingerprint = JSON.stringify(input);
      if (kept.current === null || kept.current.fingerprint !== fingerprint) {
        kept.current = { fingerprint, key: crypto.randomUUID() };
      }
      return kept.current.key;
    },

    /**
     * Забыть ключ. Зовётся после удачи: следующий запрос — другой объект, и ключ ему
     * нужен свой. У выпуска токена это заодно снимает возможность повторить выпуск и
     * получить тот же секрет ещё раз.
     */
    forget(): void {
      kept.current = null;
    },
  };
}
