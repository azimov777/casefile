/**
 * `Intl` на выбранном языке: разбор готовых форматтеров по языкам и форматирование
 * чисел.
 *
 * Язык сюда приходит параметром и нигде не читается из глобального состояния: то же
 * правило, по которому «сейчас» приходит параметром в `time.ts`. Величина, взятая
 * из окружения молча, делает результат функции зависящим от того, что кто-то сделал
 * с этим окружением раньше.
 */

import type { Language } from '../../i18n';

/**
 * Форматтер на язык, созданный один раз.
 *
 * `Intl.DateTimeFormat` и его соседи дороги в создании: они разбирают запрошенную
 * локаль и собирают правила вывода. В списке из сотни строк подпись времени рисуется
 * сотни раз за отрисовку, и создание на месте съедало бы кадр целиком.
 *
 * Разбор, а не одна константа: языков в интерфейсе больше одного, и константа
 * на модуле — это тот самый прошитый язык, от которого уходит UI-79. Разбор невелик
 * по определению: ключей в нём столько же, сколько языков в `LANGUAGES`.
 */
export function perLanguage<T>(make: (language: Language) => T): (language: Language) => T {
  const ready = new Map<Language, T>();

  return (language) => {
    const known = ready.get(language);
    if (known !== undefined) return known;

    const fresh = make(language);
    ready.set(language, fresh);
    return fresh;
  };
}

const decimal = perLanguage((language) => new Intl.NumberFormat(language));

/**
 * Число для человека на языке интерфейса: `1 234` по-русски и `1,234` по-английски.
 *
 * Разделитель разрядов — свойство языка, а не оформления, и на четырёхзначных числах
 * он виден сразу. Считает его `Intl`, своей таблицы разделителей в проекте нет.
 *
 * Отсюда форматируется **количество**: сколько задач нашлось, сколько записей в деле,
 * сколько вопросов у строки. Идентификаторы контракта (`#12` у записи) и порядковые
 * места (номер страницы в ряду) числом-количеством не являются и разделителя
 * не получают: `#1 234` — это не номер записи.
 *
 * Количество внутри фразы форматирует не эта функция, а сам `i18next` — `{{count, number}}`
 * в словаре. Правило то же и `Intl` тот же; разница только в том, кто зовёт.
 */
export function formatNumber(value: number, language: Language): string {
  return decimal(language).format(value);
}
