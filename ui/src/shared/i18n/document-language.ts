import { currentLanguage, i18n } from './i18n';

/**
 * Что страница сообщает о себе браузеру и программе чтения с экрана: язык разметки
 * и заголовок вкладки.
 *
 * `lang` — не украшение. По нему средство чтения с экрана выбирает голос и правила
 * произношения, а браузер — правила переноса слов. Английская страница, объявленная
 * русской, читается вслух русским голосом по-английски, и человек, который слушает
 * интерфейс, а не смотрит на него, получает кашу.
 *
 * Заголовок вкладки — единственная подпись интерфейса, живущая вне разметки: её видно
 * в списке вкладок, в истории и в закладках, и на чужом языке она там и останется.
 *
 * Почему не провайдер с `useEffect`: тот отработает **после** первой отрисовки, то есть
 * первый кадр страница проживёт с языком из `index.html`. Здесь же ни отрисовки, ни
 * React не нужно: экземпляр `i18next` готов к моменту импорта (`initAsync: false`),
 * поэтому язык известен ещё до того, как появится корень приложения.
 *
 * Возвращает отписку — она нужна тесту; приложение зовёт эту функцию один раз
 * на весь свой век и отписываться ему не от чего.
 */
export function syncDocumentLanguage(): () => void {
  const apply = (): void => {
    document.documentElement.lang = currentLanguage();
    document.title = i18n.t('app.name', { ns: 'ui' });
  };

  apply();
  i18n.on('languageChanged', apply);

  return () => {
    i18n.off('languageChanged', apply);
  };
}
