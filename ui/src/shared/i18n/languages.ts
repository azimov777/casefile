/**
 * Языки интерфейса: единственное место, где перечислено, на скольких языках говорит
 * трекер. Добавить язык — вписать его сюда и положить словарь рядом
 * (`dictionaries/<язык>`); экранов это не касается.
 */

/**
 * Название языка на нём самом, а не в переводе.
 *
 * Человек, открывший список на непонятном ему языке, обязан узнать там свой: `English`
 * посреди русского интерфейса ищется глазами, «английский» — нет. Поэтому названия
 * не переезжают в словари и не переводятся никогда.
 */
export const LANGUAGE_NAMES = {
  en: 'English',
  ru: 'Русский',
} as const;

export type Language = keyof typeof LANGUAGE_NAMES;

/** Порядок перечисления — порядок в переключателе; первым стоит язык по умолчанию. */
export const LANGUAGES = Object.keys(LANGUAGE_NAMES) as Language[];

/**
 * Язык по умолчанию — английский, а не запасной перевод русского: установка, поднятая
 * человеком с английским браузером, обязана открыться английской (решение владельца
 * от 9 сентября 2026, `UI-76`).
 */
export const DEFAULT_LANGUAGE: Language = 'en';

/**
 * Ключ хранилища выбранного языка — рядом с ключом токена (`shared/api/token.ts`)
 * и по тому же образцу `tracker.<что>`. В адрес страницы язык не попадает: второй
 * источник истины пришлось бы разводить приоритетом, а присланная ссылка переключала бы
 * язык тому, кому её прислали.
 */
export const LANGUAGE_STORAGE_KEY = 'tracker.language';

export function isLanguage(value: string | undefined): value is Language {
  return value !== undefined && value in LANGUAGE_NAMES;
}
