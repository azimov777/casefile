import { en } from './en';
import { ru } from './ru';

/**
 * Словари всех языков, вшитые в сборку.
 *
 * Отложенной загрузки по сети нет намеренно: два словаря весят единицы килобайт,
 * а сетевой запрос за подписями дал бы кадр без текста и второе состояние загрузки
 * на каждом экране. Станет языков много — это отдельная задача с измеренным поводом.
 *
 * Словари лежат в `shared`, а не в своих срезах: слой `shared` не вправе импортировать
 * `features` и `pages` (сторож `steiger`), а собрать их где-то надо. Разделение по
 * срезам держит имя пространства внутри словаря, а не место файла. Отвергнутая
 * развилка — словарь в каждом срезе с саморегистрацией через `addResourceBundle`:
 * регистрация стала бы побочным действием импорта, и сборщик вправе выбросить словарь,
 * если из среза больше ничего не взяли.
 */
export const dictionaries = { en, ru } as const;

export { en, ru };
