import { i18n } from '@/shared/i18n';

/**
 * Подписи из словаря — тем же ключом, каким их зовёт код.
 *
 * Тест, повторивший подпись строкой, ломается от правки формулировки и молчит о
 * пропавшем ключе. Взятая ключом подпись ведёт себя наоборот: формулировку правят
 * в одном месте, а исчезнувший ключ роняет сборку прямо здесь.
 *
 * Язык не закреплён (`getFixedT(null, …)`): он берётся у экземпляра в момент вызова,
 * то есть тот самый, который подставил `renderApp`. Поэтому один и тот же `say.ui(…)`
 * говорит по-английски в английском тесте и по-русски в русском.
 *
 * Подстановки и множественное число считает сам `i18next`: `say.tasks('found', { count: 2 })`
 * даёт ровно ту строку, что стоит на экране, — включая форму слова.
 */
export const say = {
  ui: i18n.getFixedT(null, 'ui'),
  login: i18n.getFixedT(null, 'login'),
  tasks: i18n.getFixedT(null, 'tasks'),
  task: i18n.getFixedT(null, 'task'),
  case: i18n.getFixedT(null, 'case'),
  questions: i18n.getFixedT(null, 'questions'),
  errors: i18n.getFixedT(null, 'errors'),
};
