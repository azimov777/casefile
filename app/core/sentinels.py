"""Признак «значение не передано» — один на весь проект.

Соглашения требуют различать «поле не передано» и «поле передано как null» на уровне
типов, а не договорённостью в голове. Механика для этого нужна и в схемах `PATCH`
(`app/api/schemas/common.py`), и в сценариях: `assignee`, `deadline` и `resolution`
задачи очищаются именно передачей `null`, а MCP и автоматика зовут сценарий напрямую,
мимо схем FastAPI.

Поэтому сентинел живёт в `core`, а не в схемах API: `services` не имеет права зависеть
от `api`, а две копии одного признака рано или поздно разъедутся — и один и тот же
`null` начнёт значить «очистить» в REST и «не трогать» в MCP. По той же причине здесь же
живёт `unset_field`: поля частичного изменения объявляют и схемы REST, и схемы аргументов
инструментов MCP, а `api` и `mcp` друг от друга не зависят.
"""

from typing import Any, Self

from pydantic import Field


class UnsetType:
    """Тип-одиночка сентинела. Существует ради двух свойств: ложности и `repr`.

    Ложность нужна, чтобы `if value:` на непереданном поле вёл себя как на пустом, а не
    падал в истину на «каком-то объекте». `repr` — чтобы значение в трассировке и в
    отладочном выводе читалось как `UNSET`, а не как `<object at 0x...>`.
    """

    __slots__ = ()
    _instance: UnsetType | None = None

    def __new__(cls) -> Self:
        if cls._instance is None:
            cls._instance = super().__new__(cls)
        return cls._instance

    def __bool__(self) -> bool:
        return False

    def __repr__(self) -> str:
        return "UNSET"


#: Значение по умолчанию для параметров и полей, которые можно не передавать. Тип
#: `Any` — намеренно: сентинел не должен попадать в объявленный тип поля, иначе он
#: утечёт в OpenAPI и в сгенерированный клиент.
UNSET: Any = UnsetType()


def is_set(value: Any) -> bool:
    """Значение передали. Сравнение по идентичности: `==` у чужого типа переопределяемо."""
    return value is not UNSET


def unset_field(**kwargs: Any) -> Any:
    """Поле схемы частичного изменения, которое можно не передавать.

    Поле объявляется своим настоящим типом (`str`, а не `str | None`), а значением по
    умолчанию получает `UNSET`. Следствия — все три нужные сразу:

    - `null` не проходит валидацию, потому что `None` не входит в тип поля;
    - в схеме (OpenAPI у REST, `input_schema` у инструмента MCP) поле не помечено
      nullable, и клиент не даст отправить `null` там, где он запрещён;
    - `model_dump(exclude_unset=True)` возвращает ровно переданные поля.

    Поле, у которого `null` осмысленно (очистить исполнителя, снять дедлайн),
    объявляется как `T | None` с тем же `unset_field()`: тогда различимы все три
    состояния — не передано, передано значение, передано `null`.

    `default_factory`, а не `default`: значение по умолчанию Pydantic пытается положить
    в JSON-схему, сентинел не сериализуется, и генерация схемы сыпет предупреждениями.
    Фабрику Pydantic при построении схемы не вызывает, поэтому предупреждения нет.
    """
    return Field(default_factory=lambda: UNSET, **kwargs)
