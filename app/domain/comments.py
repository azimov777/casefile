"""Комментарии: ограничения текста, разбор упоминаний, имя поля в журнале.

Чистый Python: ни ORM, ни HTTP. Правила живут здесь, а не в схемах запросов, потому
что тот же сценарий зовут MCP и автоматика — они идут мимо FastAPI, и правило,
записанное только в схеме, для них не существует.

## Комментарий человека и комментарий агента — одна сущность

Отдельной «системной» записи для сообщений автоматики нет и заводить её нельзя.
Автоматика пишет обычный комментарий от имени системного актора, а различает их тип
актора (`app/domain/actors.py`, `ActorType`). Вторая сущность означала бы вторую ленту
обсуждения, второй набор эндпоинтов и второй формат события — при том, что читателю
нужна одна лента в хронологическом порядке.

## Цепочек ответов нет, и это решение

Поля «ответ на комментарий» у комментария нет. Ответ выражается двумя средствами,
которые уже есть: цитатой отрывка в Markdown и упоминанием того, кому отвечают. Так
обсуждение остаётся плоской лентой — её можно читать сверху вниз, листать курсором и
не тянуть за собой обход дерева при каждом чтении.

Следствие, о котором надо знать: адресность держится на упоминаниях, поэтому разбор
`@ключ` — не украшение, а единственная связь ответа с тем, кому он адресован.

## Упоминания разбираются один раз, при сохранении

`@ключ_актора` вынимается из текста в момент записи и складывается отдельным полем.
Разбирать текст при каждой доставке уведомления значило бы гонять регулярное выражение
по всей ленте на каждое событие — и получать разные результаты, если правила разбора
однажды поменяются.
"""

import re
from collections.abc import Iterable

from app.domain.actors import normalize_actor_key
from app.domain.errors import InvalidCommentBodyError

#: Потолок длины комментария. Ограничение неочевидное, поэтому названо прямо: текст
#: уезжает в каждое событие и в каждое уведомление, и мегабайтный комментарий сделал
#: бы неподъёмными и то, и другое. Совпадает с потолком описания задачи.
MAX_COMMENT_LENGTH = 65_536

#: Длина отрывка комментария в записи журнала изменений. История задачи читается
#: страницами, и несколько правок комментария на 64 килобайта сделали бы её
#: неподъёмной; полный текст при этом никуда не девается — он лежит в самой ленте и
#: целиком уходит в событие.
COMMENT_EXCERPT_LENGTH = 140

#: Имя поля в журнале изменений задачи. Входит в `SYSTEM_FIELD_KEYS`
#: (`app/domain/fields.py`), поэтому кастомное поле с таким ключом завести нельзя и
#: запись истории читается однозначно.
COMMENTS_CHANGE_FIELD = "comments"

#: Упоминание: `@` и ключ актора по шаблону из `app/domain/actors.py`.
#:
#: Границы обязательны с обеих сторон. Слева — чтобы `alice@bob` (адрес почты, часть
#: пути) не превращалось в упоминание `bob`. Справа — чтобы `@aliceX` не считалось
#: упоминанием `alice`: без этой границы регулярное выражение съело бы допустимую
#: часть ключа и молча адресовало бы комментарий не тому актору.
MENTION_PATTERN = r"(?<![0-9A-Za-z_@])@([a-z][a-z0-9_]{1,63})(?![0-9A-Za-z_])"
_MENTION_RE = re.compile(MENTION_PATTERN)


def validate_body(body: str) -> str:
    """Проверяет текст комментария и возвращает канонический вид.

    Пустой комментарий отвергается, а не сохраняется пустым: в ленте он выглядел бы
    сбоем интерфейса, а уведомление о нём было бы уведомлением ни о чём. Пробелы по
    краям снимаются — иначе один и тот же текст с лишним переводом строки считался бы
    изменением и порождал бы правку с пустой разницей.
    """
    normalized = body.strip()
    if not normalized:
        raise InvalidCommentBodyError(details={"field": "body", "reason": "required"})
    if len(normalized) > MAX_COMMENT_LENGTH:
        raise InvalidCommentBodyError(
            details={
                "field": "body",
                "reason": "too_long",
                "max": MAX_COMMENT_LENGTH,
                "got": len(normalized),
            },
        )
    return normalized


def extract_mentions(body: str) -> list[str]:
    """Ключи акторов, упомянутых в тексте, без повторов и в порядке появления.

    Возвращаются **синтаксически возможные** ключи, а не проверенные по базе: домен
    базы не знает. Отбор существующих акторов делает сценарий, и делает это
    осознанно — упоминание несуществующего ключа остаётся текстом и в поле адресатов
    не попадает (`app/services/comments.py`).

    Порядок сохраняется, чтобы поле упоминаний было воспроизводимым: набор, собранный
    множеством, менял бы порядок от запуска к запуску и делал бы разницу «было →
    стало» в журнале шумной.
    """
    found: list[str] = []
    seen: set[str] = set()
    for match in _MENTION_RE.finditer(body):
        key = normalize_actor_key(match.group(1))
        if key in seen:
            continue
        seen.add(key)
        found.append(key)
    return found


def mentions_differ(before: Iterable[str], after: Iterable[str]) -> bool:
    """Изменился ли набор адресатов. Порядок значения не имеет, состав — имеет."""
    return set(before) != set(after)
