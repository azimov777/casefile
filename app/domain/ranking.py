"""Разреженные позиции: одна арифметика порядка на весь проект.

Чистый Python: ни ORM, ни HTTP. Здесь лежит то, чем пользуются и чеклист задачи
(`app/domain/checklists.py`), и ранжирование карточек на доске
(`app/domain/boards.py`). Второй реализации быть не должно: формула тривиальна ровно
до первого краевого случая — исчерпания зазора, — а разошедшись, две копии дали бы
два элемента на одной позиции и произвольный порядок между ними.

## Почему целые с шагом, а не порядковый номер

Позиция — целое число с большим шагом между соседями, а не номер по порядку. Смысл
один: перемещение обязано менять **одну** строку. При сплошной нумерации перенос
первого элемента в конец переписал бы весь список.

Зазор между соседями конечен: каждая вставка в одно и то же место делит его пополам.
Когда он исчерпан, `position_between` возвращает `None` — это не ошибка, а сигнал
вызывающему перенумеровать список и повторить попытку. Обработать этот случай
обязательно: подстановка «чего-нибудь рядом» даёт два элемента на одной позиции, и
порядок между ними становится произвольным.

## Почему не дробные позиции

`numeric` сняла бы исчерпание зазора, но подменила бы его худшей проблемой: двоичная
дробь делится пополам бесконечно, и после сотни вставок в одно место позиция
превращается в число, которое база хранит, а человек не читает.
"""

#: Шаг между соседними позициями. Степень двойки не случайна: вставка делит зазор
#: пополам, и с шагом 1024 подряд помещается десять вставок в одно и то же место,
#: прежде чем понадобится перенумерация.
POSITION_STEP = 1024


def next_position(last: int | None) -> int:
    """Позиция для элемента, добавляемого в конец списка."""
    return POSITION_STEP if last is None else last + POSITION_STEP


def position_between(before: int | None, after: int | None) -> int | None:
    """Позиция строго между соседями или `None`, если зазор исчерпан.

    `None` означает «перенумеруй список и попробуй ещё раз», а не «ошибка»: вызывающая
    сторона обязана обработать этот случай, иначе два элемента однажды получат одну
    позицию и порядок между ними станет произвольным.

    Границы списка выражены `None`: `before is None` — вставка в начало, `after is
    None` — в конец. Вставка в начало делит пополам позицию первого элемента и упирается
    в ноль — это тоже исчерпание зазора: отрицательные позиции запрещены, они делают
    порядок нечитаемым в дампе и ломают предположение «позиция растёт вниз по списку».
    """
    if before is None:
        if after is None:
            return POSITION_STEP
        return after // 2 if after >= 2 else None
    if after is None:
        return before + POSITION_STEP
    if after - before < 2:
        return None
    return (before + after) // 2


def rebalanced_positions(count: int) -> list[int]:
    """Позиции для перенумерации списка: снова с полным шагом между соседями.

    Порядок элементов сохраняется, меняются только числа. Вызывается редко — когда
    зазор в одном месте исчерпан, — и переписывает список целиком: это единственная
    операция порядка, которая трогает больше одной строки.
    """
    return [POSITION_STEP * (index + 1) for index in range(count)]
