"""Токены доступа: генерация секрета и его хеширование.

Полное значение токена существует ровно один раз — в ответе на его выпуск. В базе
лежит только хеш, поэтому украденный дамп базы не даёт доступа к API.
"""

import hashlib
import secrets

#: Префикс отличает наш токен от чужого секрета в логах и в переменных окружения.
TOKEN_PREFIX = "trk_"

#: 32 байта энтропии — 256 бит. Перебор такого секрета невозможен, поэтому медленная
#: функция вывода ключа (bcrypt, argon2) здесь не нужна: она защищает пароли, у которых
#: энтропии мало. Быстрый хеш взамен даёт поиск токена одним запросом по индексу.
TOKEN_ENTROPY_BYTES = 32

#: Длина hex-представления SHA-256: под неё задана колонка `api_tokens.token_hash`.
TOKEN_HASH_LENGTH = 64


def generate_token() -> str:
    """Новый токен доступа. Возвращается вызывающему один раз и нигде не сохраняется."""
    return f"{TOKEN_PREFIX}{secrets.token_urlsafe(TOKEN_ENTROPY_BYTES)}"


def hash_token(raw_token: str) -> str:
    """Хеш токена для хранения и поиска.

    Значение обрезается по краям: токен часто копируют вместе с пробелом или переводом
    строки, и без нормализации такой токен молча перестаёт работать.
    """
    return hashlib.sha256(raw_token.strip().encode("utf-8")).hexdigest()
