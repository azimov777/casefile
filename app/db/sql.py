"""Кусочки SQL, общие для нескольких репозиториев.

Модуль существует ради одного правила: выражение, которое где-то уже написано, не
пишется второй раз. Экранирование шаблона `LIKE` выглядит тривиальным, и именно поэтому
его переписывают по месту — а расходятся такие копии молча: одна ищет тег `100_percent`,
другая находит по нему `100xpercent`.
"""

from typing import Any

#: Символ экранирования в `LIKE`. Обратный слеш, а не что-то экзотическое: он и так
#: экранирует сам себя в шаблоне, и другой символ пришлось бы объяснять каждому чтению.
LIKE_ESCAPE = "\\"


def like_pattern(value: str) -> str:
    """Подстрока → шаблон `%...%` с экранированными `%`, `_` и `\\`.

    Без экранирования пользовательский ввод становится шаблоном: `100_percent` искался
    бы как «сто, любой символ, percent». Сбой молчаливый — выдача просто содержит лишнее,
    и заметить это можно только на редком значении.
    """
    escaped = (
        value.replace(LIKE_ESCAPE, LIKE_ESCAPE * 2)
        .replace("%", f"{LIKE_ESCAPE}%")
        .replace("_", f"{LIKE_ESCAPE}_")
    )
    return f"%{escaped}%"


def ilike_contains(column: Any, value: str) -> Any:
    """Регистронезависимое вхождение подстроки. Одна форма на весь проект.

    `escape` передаётся явно: без него PostgreSQL не знает, что обратный слеш в шаблоне
    что-то экранирует, и экранирование выше оказалось бы бессмысленным.
    """
    return column.ilike(like_pattern(value), escape=LIKE_ESCAPE)
