"""Комментарий к задаче: одна лента обсуждения на человека, агента и автоматику.

Отдельной сущности для сообщений автоматики нет: она пишет тот же комментарий от
имени системного актора, а различает их тип актора. Причина в читателе — ему нужна
одна лента в хронологическом порядке, а не две, которые придётся склеивать на клиенте.

## Удаление мягкое

Строка остаётся, у неё проставляется `deleted_at`, а текст затирается. Дыра в
обсуждении хуже плашки «комментарий удалён»: соседние реплики теряют контекст, а
уведомление, ушедшее до удаления, начинает ссылаться в никуда.

Текст затирается, а не прячется в выдаче: удаление обязано убирать сказанное из базы,
иначе «удалил» означает «спрятал от интерфейса», и первый же дамп это опровергнет.
"""

from __future__ import annotations

import uuid
from datetime import datetime

from sqlalchemy import ForeignKey, Index, Text, func, text
from sqlalchemy.dialects.postgresql import JSONB
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.db.base import BaseModel
from app.db.models.actor import Actor
from app.db.models.issue import Issue


class Comment(BaseModel):
    """Реплика в обсуждении задачи.

    Цепочек ответов нет намеренно: ответ выражается цитатой в тексте и упоминанием
    того, кому отвечают (`app/domain/comments.py`). Поэтому у комментария нет ссылки
    на родителя, а лента остаётся плоской и листается курсором.

    `mentions` — ключи акторов, разобранные из текста при сохранении. Отдельным полем,
    а не разбором при доставке: на упоминания подписаны уведомления (задача 14), и
    гонять регулярное выражение по всей ленте на каждое событие незачем.
    """

    __tablename__ = "comments"
    __table_args__ = (
        # Основной и единственный запрос: лента одной задачи страницами. Порядок
        # колонок повторяет `WHERE issue_id = ? ORDER BY created_at, id` — курсорная
        # пагинация проекта идёт по паре `(created_at, id)`.
        Index("ix_comments_issue_id_created_at_id", "issue_id", "created_at", "id"),
        # «Что писал этот актор» — запрос аудита и будущей ленты агента; предыдущий
        # индекс начинается с задачи и на такой вопрос не отвечает.
        Index("ix_comments_author_id", "author_id"),
        # «Где меня упомянули» — запрос движка уведомлений. GIN по массиву ключей
        # обслуживает `mentions ? 'alice'`; без него подписка на упоминания означала
        # бы последовательное чтение всех комментариев установки.
        Index("ix_comments_mentions", "mentions", postgresql_using="gin"),
        # Полнотекстовый поиск по обсуждению идёт `ILIKE '%...%'` и без триграммного
        # индекса означал бы чтение всех комментариев установки на каждый запрос.
        # Текст удалённого комментария затёрт, поэтому исключать его отдельным
        # условием не нужно: пустая строка не совпадёт ни с чем.
        Index(
            "ix_comments_body_trgm",
            "body",
            postgresql_using="gin",
            postgresql_ops={"body": "gin_trgm_ops"},
        ),
    )

    # `ondelete="CASCADE"`: задача удаляется насовсем, и обсуждение вместе с ней.
    # Отдельных событий об этом нет — подписчику достаточно `issue.deleted`, как и в
    # случае со связями (`docs/notes/links.md`).
    issue_id: Mapped[uuid.UUID] = mapped_column(
        ForeignKey("issues.id", ondelete="CASCADE"),
        nullable=False,
    )
    # Без `ondelete`: акторов не удаляют, их отключают, — и реплика обязана остаться
    # читаемой вместе с именем того, кто её написал.
    author_id: Mapped[uuid.UUID] = mapped_column(ForeignKey("actors.id"), nullable=False)

    # Пустая строка у удалённого комментария, непустая у живого. Не `NULL`: «текста
    # нет» выражает `deleted_at`, и два независимых признака одного состояния однажды
    # разъехались бы.
    body: Mapped[str] = mapped_column(Text, nullable=False)

    mentions: Mapped[list[str]] = mapped_column(
        JSONB,
        default=list,
        server_default=text("'[]'::jsonb"),
        nullable=False,
    )

    # Время последней правки текста, а не любой записи в строку. `updated_at` из общей
    # примеси меняется и при мягком удалении, поэтому «отредактирован» по нему не
    # определить: в ленте появилась бы пометка «изменён» у только что удалённого.
    edited_at: Mapped[datetime | None] = mapped_column(default=None, nullable=True)
    deleted_at: Mapped[datetime | None] = mapped_column(default=None, nullable=True)

    # Отметка времени идёт вперёд внутри транзакции, как у журнала изменений и outbox:
    # `now()` — время начала транзакции, и пачка комментариев, написанная автоматикой
    # за один проход, получила бы одну отметку. Сортировка по паре `(created_at, id)`
    # выродилась бы в сортировку по случайным UUID, и ответ встал бы раньше реплики,
    # на которую отвечает.
    created_at: Mapped[datetime] = mapped_column(
        server_default=func.clock_timestamp(),
        nullable=False,
    )

    # Ключ автора нужен каждой странице ленты, а `selectin` берёт всех акторов
    # страницы одним запросом и переиспользует уже загруженных.
    author: Mapped[Actor] = relationship(lazy="selectin")
    # Задача — наоборот, `raise`: комментарий всегда читается через свою задачу, и та
    # у сценария уже загружена со всеми справочниками. `selectin` тянул бы её (а с ней
    # очередь, статус, тип, акторов) на каждую страницу ленты ради данных, которые у
    # вызывающего кода есть. Ленивая загрузка в async-сессии при этом падает
    # `MissingGreenlet` в самом неудобном месте, поэтому не «не трогать», а `raise`:
    # случайное обращение становится понятной ошибкой сразу.
    issue: Mapped[Issue] = relationship(lazy="raise")

    @property
    def is_deleted(self) -> bool:
        """Признак для API и сценариев: у удалённого комментария нет текста."""
        return self.deleted_at is not None
