"""Очередь изменений: одна консультативная блокировка на все мутирующие сценарии.

Блокировка заводилась ради ленты, а держит теперь две вещи сразу, и обе обязан знать
всякий, кто пишет новый сценарий, меняющий состояние.

## Порядок `seq` совпадает с порядком фиксации

`seq` выдаёт `IDENTITY` в момент `INSERT`, а видимой строка становится в момент
`COMMIT`. Без общей очереди два порядка расходятся: транзакции, пишущие в **разные**
задачи (блокировка строки задачи их не сериализует), могут получить номера 10 и 11 и
закоммититься наоборот. Читатель ленты, дошедший до 11, запись 10 не увидит уже
никогда — курсор двигается только вперёд, а молча потерянная запись означает
назначателя, не узнавшего о закрытии задачи.

## Факты перехода читаются под той же очередью

Проверки перехода смотрят на блокеры, детей и вердикты обычным `SELECT`, а фиксацию
задачи страхует только её собственная `version`. Постановка связи `blocked_by` и
рождение ребёнка версию переводимой задачи не меняют, поэтому без общей очереди
проходил бы такой сценарий: T1 прочитала «детей нет», T2 добавила ребёнка и
зафиксировалась, T1 закрыла родителя — закрытый родитель с открытым ребёнком, и обе
транзакции по-своему правы. Очередь, взятая **до** чтения фактов, делает такое
чередование невозможным: пока T1 не зафиксировалась, T2 даже не начала читать.

Цена — изменения по всей установке идут по одному до конца транзакции. Она не выросла:
любой мутирующий сценарий подшивает запись в дело и потому и так держал эту очередь до
конца транзакции — менялся только момент захвата.

## Порядок захвата единый

**Сначала** очередь изменений, потом строки: строка задачи
(`EntryRepository.allocate_no`) и строка очереди (`QueueRepository.allocate_task_number`).
Обратный порядок даёт взаимную блокировку: один держал бы строку и ждал очереди, другой
держал бы очередь и ждал строки. Новый сценарий, которому нужна ещё одна строка под
блокировкой, берёт её после очереди, а не до.
"""

from sqlalchemy import text
from sqlalchemy.ext.asyncio import AsyncSession

from app.db.models.task import Task

#: Ключ консультативной блокировки. Число — ASCII слова `journal`, под которым очередь
#: родилась: так в `pg_locks` видно, чья это блокировка, и так она заведомо не совпадёт
#: с чужим ключом в той же базе.
CHANGES_LOCK = 0x6A6F75726E616C


async def lock_changes(session: AsyncSession, *tasks: Task) -> None:
    """Занимает очередь изменений и перечитывает названные задачи уже под ней.

    Вызывается **первым делом** в каждом сценарии, который меняет состояние: до чтения
    фактов, до проверок и до любой блокировки строк. Блокировка отпускается коммитом
    или откатом, отдельного снятия нет; повторный захват в той же транзакции законен и
    ничего не стоит, поэтому подшивка записи берёт её ещё раз, не спрашивая, взял ли её
    сценарий выше.

    Перечитывание — не украшение. Задачи приезжают в сценарий прочитанными **до**
    блокировки: их читает роутер или инструмент, чтобы разрешить ключи в объекты. Пока
    сценарий стоял в очереди, соседняя транзакция могла закрыть задачу, и проверка
    «закрытую не трогаем» смотрела бы на устаревший снимок из карты объектов сессии.
    `refresh` возвращает строку такой, какая она в базе сейчас, — за счёт `READ
    COMMITTED` это состояние после всех зафиксировавшихся соседей.

    Отсюда требование к вызывающему: перечитывать задачу можно только до собственных
    правок. `refresh` снимает с объекта незаписанные изменения, и вызов в середине
    сценария потерял бы их молча.
    """
    await session.execute(text("SELECT pg_advisory_xact_lock(:key)"), {"key": CHANGES_LOCK})
    for task in tasks:
        await session.refresh(task)
