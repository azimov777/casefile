"""Текст скила: промпт целиком и выжимка для `instructions`.

Дисциплина работы с делом живёт в `skill/tracker-agent/SKILL.md` — единственном исходном
тексте (`CONCEPT.md`, 5.3). Отсюда приложение берёт два представления одного и того же:

- промпт `tracker-discipline` отдаёт файл **целиком**, как есть;
- `instructions` при инициализации — раздел «Кратко», потому что инструкция уезжает
  клиенту при подключении и читается моделью раньше любого вызова, а полный скил в неё
  не помещается по смыслу: он длиннее, чем то, что клиент готов держать всегда.

Второй копии этого текста в коде нет и быть не должно. Скопированная выжимка разошлась бы
со скилом при первой же правке дисциплины, и агент получил бы две несогласованные
инструкции — ту, что установлена в харнесс, и ту, что раздаёт сервер.

## Файл читается при импорте, и это осознанно

Отсутствие файла роняет процесс на старте, а не отдаёт пустой промпт при первом
обращении. Пустая инструкция — худший из исходов: сервер выглядит здоровым, а агент
работает без дисциплины и об этом не знает.

Из того же следует требование к сборке: `skill/` обязан попадать в образ. В прод-образ
он копируется явно (`docker/Dockerfile.prod`), в дев-контуре приезжает вместе с
исходниками.
"""

from pathlib import Path

#: Скил лежит рядом с кодом, а не внутри пакета: его устанавливают в харнесс как обычный
#: скил, и прятать его в `app/` значило бы заставлять человека доставать текст из недр
#: приложения.
SKILL_PATH = Path(__file__).resolve().parents[2] / "skill" / "tracker-agent" / "SKILL.md"

#: Имя промпта. То же самое имя названо в `CONCEPT.md`, 5.2.
PROMPT_NAME = "tracker-discipline"

#: Заголовок раздела, который уезжает в `instructions`.
SUMMARY_HEADING = "## Кратко"

#: Начало любого другого раздела: им же ограничивается выжимка.
_HEADING_PREFIX = "## "


def read_skill() -> str:
    """Текст скила целиком. Именно то, что видит харнесс, установивший скил."""
    return SKILL_PATH.read_text(encoding="utf-8")


def summary_section(text: str) -> str:
    """Раздел «Кратко» без заголовка.

    Разбор простой намеренно: раздел ограничен следующим заголовком второго уровня, и
    более умный разбор markdown тут не нужен — формат файла задаём мы сами.

    Отсутствие раздела — ошибка сборки, а не пустая строка: `instructions` читается
    моделью раньше любого вызова, и молча отдать пустоту значило бы выпустить агента
    без дисциплины.
    """
    _, separator, rest = text.partition(f"{SUMMARY_HEADING}\n")
    if not separator:
        raise ValueError(
            f"{SKILL_PATH} has no {SUMMARY_HEADING!r} section: the MCP server takes its "
            "`instructions` from it"
        )
    body, *_ = rest.split(f"\n{_HEADING_PREFIX}", 1)
    return body.strip()


#: Полный текст скила — то, что отдаёт промпт `tracker-discipline`.
SKILL_TEXT = read_skill()

#: Выжимка для `instructions` сервера.
INSTRUCTIONS = summary_section(SKILL_TEXT)
