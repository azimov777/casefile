"""Текст скила для промпта `tracker-discipline`.

Дисциплина работы с делом живёт в `skill/tracker-agent/SKILL.md` — единственном исходном
тексте (`CONCEPT.md`, 5.3). Промпт `tracker-discipline` отдаёт файл **целиком**, как есть.

`instructions` сервера из скила больше не берутся: у них свой текст о том, как
пользоваться сервером (`app/mcp/instructions.md`, `TRK-142`). Раздел «Кратко» в них не
помещался — Claude Code обрезает `instructions` на 2048-м символе.

## Файл читается при импорте, и это осознанно

Отсутствие файла роняет процесс на старте, а не отдаёт пустой промпт при первом
обращении. Пустая инструкция — худший из исходов: сервер выглядит здоровым, а агент
работает без дисциплины и об этом не знает.

Из того же следует требование к сборке: `skill/` обязан попадать в образ. В прод-образ
он копируется явно (`docker/Dockerfile.prod`), в дев-контуре приезжает вместе с
исходниками.
"""

from pathlib import Path

#: Скил лежит рядом с кодом, а не внутри пакета: его устанавливают в харнесс как обычный
#: скил, и прятать его в `app/` значило бы заставлять человека доставать текст из недр
#: приложения.
SKILL_PATH = Path(__file__).resolve().parents[2] / "skill" / "tracker-agent" / "SKILL.md"

#: Имя промпта. То же самое имя названо в `CONCEPT.md`, 5.2.
PROMPT_NAME = "tracker-discipline"


def read_skill() -> str:
    """Текст скила целиком. Именно то, что видит харнесс, установивший скил."""
    return SKILL_PATH.read_text(encoding="utf-8")


#: Полный текст скила — то, что отдаёт промпт `tracker-discipline`.
SKILL_TEXT = read_skill()
