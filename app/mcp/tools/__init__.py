"""Инструменты MCP: тонкий слой поверх сценариев.

Инструменты лежат в предметных группах — папка на группу, файл на инструмент
(`<группа>/<имя>.py`). В файле рядом стоят описание, аргументы, форма ответа и вызов
сценария; общее для нескольких инструментов группы — в её `arguments.py` и `views.py`,
общее для разных групп — в `app/mcp/arguments.py` и `app/mcp/views.py`.

Инструмент подключается к серверу строкой в реестре своей группы (`TOOLS` в `__init__.py`
группы), группа — строкой в `REGISTRARS` ниже. Оба списка — единственные места
подключения: забытый модуль виден как отсутствующая строка, а не как молча пропавший
инструмент. Порядок групп и порядок внутри группы вместе дают порядок `tools/list`.

## Границы, общие для всех инструментов

- **Один инструмент — один вид действия.** Составных нет: у составного вызова отказ
  второй половины оставляет первую применённой, а агент видит одну ошибку и не знает,
  что именно случилось.
- **Результат — данные.** Ни подсказок, ни советов, что делать дальше: ход агента
  задают `instructions` и метадата инструмента, не тело ответа (`CONCEPT.md`, 5.2 и 6).
- **Ошибка — код и причина.** Перевод доменной ошибки один на слой
  (`app/mcp/errors.py`): агент читает `code`, `message` и подробности целиком и чинит
  вызов с первой попытки.
- **Транзакцию держит вход.** `Runtime.call` открывает сессию и фиксирует её на выходе;
  своей транзакции инструмент не открывает — иначе долгое ожидание ленты держало бы
  соединение из пула всё время сна.
"""

from collections.abc import Callable, Sequence

from app.mcp.tools import case, journal, links, registries, tasks
from app.mcp.toolset import Toolset

#: Порядок сборки. Он же порядок, в котором инструменты появляются в `tools/list`, —
#: поэтому первым идёт то, с чего начинается работа над задачей.
REGISTRARS: Sequence[Callable[[Toolset], None]] = (
    tasks.register,
    case.register,
    links.register,
    registries.register,
    journal.register,
)


def register_tools(tools: Toolset) -> None:
    """Объявляет все инструменты сервера."""
    for registrar in REGISTRARS:
        registrar(tools)
