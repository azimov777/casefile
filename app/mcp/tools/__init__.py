"""Инструменты MCP: тонкий слой поверх сценариев.

Каждый модуль объявляет свои инструменты функцией `register(tools)`, а порядок сборки
задан здесь. Список модулей — единственное место, где новый инструмент подключается к
серверу: забытый модуль виден как отсутствующая строка, а не как молча пропавший
инструмент.

## Границы, общие для всех инструментов

- **Один инструмент — один вид действия.** Составных нет: у составного вызова отказ
  второй половины оставляет первую применённой, а агент видит одну ошибку и не знает,
  что именно случилось.
- **Результат — данные.** Ни подсказок, ни советов, что делать дальше: их место — скил,
  который сервер раздаёт промптом (`CONCEPT.md`, 5.2 и 6).
- **Ошибка — код и причина.** Перевод доменной ошибки один на слой
  (`app/mcp/errors.py`): агент читает `code`, `message` и подробности целиком и чинит
  вызов с первой попытки.
- **Транзакцию держит вход.** `Runtime.call` открывает сессию и фиксирует её на выходе;
  своей транзакции инструмент не открывает — иначе долгое ожидание ленты держало бы
  соединение из пула всё время сна.
"""

from collections.abc import Callable, Sequence

from app.mcp.tools import case, journal, links, registry, tasks
from app.mcp.toolset import Toolset

#: Порядок сборки. Он же порядок, в котором инструменты появляются в `tools/list`, —
#: поэтому первым идёт то, с чего начинается работа над задачей.
REGISTRARS: Sequence[Callable[[Toolset], None]] = (
    tasks.register,
    case.register,
    links.register,
    registry.register,
    journal.register,
)


def register_tools(tools: Toolset) -> None:
    """Объявляет все инструменты сервера."""
    for registrar in REGISTRARS:
        registrar(tools)
