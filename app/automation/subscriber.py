"""Подписка движка автоматики на шину событий.

Один подписчик на весь движок, а не по подписчику на правило. Причина в устройстве
шины: имя подписчика попадает в `outbox_events.delivered_to`, и повтор события идёт
только по тем, кто ещё не отработал. С подпиской на правило добавление нового правила
означало бы, что у всех уже доставленных событий появился неотработавший подписчик, — а
у правил свой журнал и свой набор защит, и повторять по ним события шине незачем.

Подписка без указания типов, то есть на все события. Перечислить только объявленные
типы было бы дешевле на один поиск в словаре, но набор типов зависел бы от того, какие
модули правил успели импортироваться к моменту регистрации, — а отбор по типу движок
делает всё равно, и делает его точнее.
"""

from sqlalchemy.ext.asyncio import AsyncSession

from app.automation import engine
from app.automation.registry import load_rules
from app.services.event_bus import EventEnvelope, subscribe

# Правила объявляются декоратором при импорте своего модуля, поэтому модули надо
# импортировать до первого события. Здесь — самое раннее место, где это гарантированно
# происходит в воркере: сам модуль импортируется реестром подписчиков при его старте.
load_rules()


@subscribe(name="automation")
async def dispatch(session: AsyncSession, event: EventEnvelope) -> None:
    """Отдаёт событие движку автоматики.

    Исключения наружу не выпускает: движок ловит падение каждого правила сам и пишет
    его в журнал срабатываний. Если бы ошибка дошла сюда, изоляция шины откатила бы
    вложенную транзакцию вместе с записями журнала — то есть ровно то, ради чего движок
    и ловит их у себя.
    """
    await engine.dispatch_event(session, event)
