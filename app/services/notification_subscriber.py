"""Подписка движка уведомлений на шину событий.

Один подписчик на все типы событий, а не по подписчику на тип. Причина в устройстве
шины: имя подписчика попадает в `outbox_events.delivered_to`, и повтор события идёт
только по тем, кто ещё не отработал. С подпиской на каждый тип добавление нового типа
события означало бы, что у всех уже доставленных событий появился неотработавший
подписчик.

Подписка без перечисления типов означает «все события», и это именно то, что нужно
инбоксу: подписка на очередь или на весь поток обязана ловить любое изменение, а не
заранее выбранный список. Отбор по типу делает подписка актора, а не шина.
"""

from sqlalchemy.ext.asyncio import AsyncSession

from app.services import notifications as notifications_service
from app.services.event_bus import EventEnvelope, subscribe


@subscribe(name="notifications")
async def deliver(session: AsyncSession, event: EventEnvelope) -> None:
    """Раскладывает событие по инбоксам подписчиков.

    Исключения наружу выпускает намеренно: изоляция шины откатит вложенную транзакцию
    этого подписчика и пометит событие для повтора, не задев ни автоматику, ни отметку
    об обработке. Проглотить ошибку здесь значило бы потерять уведомления молча — а
    инбокс это единственный канал, по которому агент вообще узнаёт о происходящем.
    """
    await notifications_service.dispatch_event(session, event)
