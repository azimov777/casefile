"""Подписка живого потока на шину событий.

Обработчик не отдаёт событие клиенту и вообще ничего не пишет — он **будит** открытые
потоки. Само событие они читают из `outbox_events` сами, каждый со своим курсором и
своим фильтром.

Почему так, а не «подписчик рассылает событие соединениям»: соединения живут в
процессах API, а подписчик работает в воркере — это разные процессы, и передать между
ними объект нечем. Оповещение PostgreSQL доходит до всех процессов сразу, а чтение по
курсору заодно решает переподключение: поток, пропустивший события, дочитывает их тем
же запросом, которым читает новые.

Подписка идёт через реестр, как и все остальные: канал наружу не имеет права требовать
правки ядра шины.
"""

from sqlalchemy.ext.asyncio import AsyncSession

from app.db.wakeup import notify_stream
from app.services.event_bus import EventEnvelope, subscribe


@subscribe(name="event_stream")
async def wake_streams(session: AsyncSession, event: EventEnvelope) -> None:
    """Будит открытые SSE-соединения: появилось новое событие.

    Оповещение уходит в транзакции воркера и доставляется слушателям при её фиксации.
    Ложное пробуждение здесь безопасно и дёшево: поток сходит в базу, не найдёт ничего
    подходящего под свой фильтр и вернётся ждать.
    """
    await notify_stream(session)
