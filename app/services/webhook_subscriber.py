"""Подписка вебхуков на шину событий.

Один подписчик на все типы событий, а не по подписчику на тип. Причина та же, что у
инбокса: имя подписчика попадает в `outbox_events.delivered_to`, и повтор события идёт
только по тем, кто ещё не отработал. С подпиской на каждый тип добавление нового типа
события означало бы, что у всех уже доставленных событий появился неотработавший
подписчик.

Подписка без перечисления типов означает «все события», и это именно то, что нужно
вебхуку: подписка на очередь или на весь поток обязана ловить любое изменение, а не
заранее выбранный список. Отбор по типу делает подписка вебхука, а не шина.

Обработчик **не отправляет HTTP**: он ставит задания в `webhook_deliveries`. Сетевой
вызов отсюда остановил бы всю очередь событий на таймауте мёртвого адреса — воркер
разбирает её по одному событию.
"""

from sqlalchemy.ext.asyncio import AsyncSession

from app.services import webhooks as webhooks_service
from app.services.event_bus import EventEnvelope, subscribe


@subscribe(name="webhooks")
async def deliver(session: AsyncSession, event: EventEnvelope) -> None:
    """Ставит задания на доставку события по подходящим адресам.

    Исключения наружу выпускает намеренно, как и подписчик инбокса: изоляция шины
    откатит вложенную транзакцию этого подписчика и пометит событие для повтора, не
    задев ни автоматику, ни уведомления. Проглотить ошибку здесь значило бы молча не
    поставить задание — то есть потерять вызов наружу без единого следа.
    """
    await webhooks_service.dispatch_event(session, event)
