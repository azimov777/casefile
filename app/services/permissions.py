"""Единая точка проверки прав.

Прав в трекере ровно одно — набор токена (`CONCEPT.md`, 3.1 и 6). Ролей, владельцев и
разрешений по роду участника нет: любую запись и любой переход может сделать кто угодно.
Вход в `in_progress` только исполнителю задачи — проверка перехода в домене
(`check_taken_by_assignee`, `app/domain/tasks.py`), а не право, и сюда она не входит.
Поэтому функция здесь одна и проверяет она одно.

Вызывается всё равно в **каждом** сценарии, включая чтение, где отказ невозможен. Это не
преждевременное усложнение, а маркер: забытый вызов виден как отсутствие строки в начале
сценария, а не как дырка в правах, которую надо искать по семнадцати роутерам и
инструментам MCP. И когда набор понадобится новому действию, менять придётся одну
строку в этом сценарии, а не искать, где ещё проверяются права.

Действие называется `<сущность>.<глагол>`: `project.create`, `token.revoke`. Строка, а не
перечисление, — сознательно: набор действий растёт каждой задачей, и общий enum пришлось
бы править при каждом новом эндпоинте. Наружу строка уезжает в `details.action` — по ней
клиент понимает, что именно ему отказано.
"""

from app.core.errors import PermissionDeniedError
from app.domain.tokens import TokenScope
from app.services.auth import Actor


def ensure_scope(actor: Actor, required: TokenScope, *, action: str) -> None:
    """Разрешает действие набору токена или бросает `PermissionDeniedError`.

    Вложенность наборов (`main` открывает всё, что открывает `task`) выражена в самом
    перечислении — `TokenScope.allows`, — чтобы фильтр инструментов MCP (задача 28)
    пользовался тем же правилом, а не своей копией цепочки условий.
    """
    if not actor.scope.allows(required):
        raise PermissionDeniedError(
            details={
                "action": action,
                "scope": actor.scope.value,
                "required_scope": required.value,
            },
        )
