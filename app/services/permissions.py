"""Единая точка проверки прав.

В v1 ролевой модели нет: любой аутентифицированный актор может всё. Функция всё равно
вызывается в каждом сценарии — и это не преждевременное усложнение, а маркер. Когда
появятся роли, наполнять придётся один файл, а не искать проверки по семнадцати
роутерам и инструментам MCP; забытый вызов будет виден как отсутствие строки в начале
сценария, а не как дырка в безопасности.

Действие называется `<сущность>.<глагол>`: `actor.create`, `token.revoke`. Строка, а не
перечисление, — сознательно: набор действий будет расти каждой задачей, и держать их
список в одном enum значило бы править этот файл при каждом новом эндпоинте.
"""

from app.core.errors import PermissionDeniedError
from app.db.models.actor import Actor


def ensure_allowed(actor: Actor, action: str, *, target: object | None = None) -> None:
    """Разрешает действие или бросает `PermissionDeniedError`.

    Сейчас отказ бывает ровно один: отключённый актор. До сценария такой актор дойти
    не должен — аутентификация отсекает его раньше, — но проверка стоит и здесь:
    сценарий вызывается ещё и из фоновых процессов, где токена нет вовсе.
    """
    if not actor.is_active:
        raise PermissionDeniedError(
            details={"actor": actor.key, "action": action, "reason": "actor_inactive"},
        )
